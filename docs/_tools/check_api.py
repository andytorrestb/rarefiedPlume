"""Check the API reference against the source tree, statically.

    python docs/_tools/check_api.py

Exit status 0 when every check passes, 1 otherwise, with one line per problem.
Nothing is imported from ``plumetools``: modules are found on disk and their
names read with ``ast``, so this runs in the documentation environment alone.

Checks:

1. every module under ``plumetools/`` belongs to a known family and has a page
   (hand-written, or generated by ``hooks.py``), and no hand-written module page
   is left for a module that no longer exists;
2. every family index page names every module of its family by dotted name,
   so a new module cannot appear without its family page being updated;
3. a hand-written module page renders its own module (``::: <module>``);
4. every ``::: target`` in any page resolves to a module, or a name defined
   in one;
5. every name in a family page's "Principal interfaces" column is defined at
   the top level of the module in that row.
"""

from __future__ import annotations

import ast
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import hooks  # noqa: E402  (the same module discovery the build uses)

ROOT = hooks.ROOT
DOCS = ROOT / "docs"
API = DOCS / hooks.API_DIR


def module_file(module: str) -> Path:
    return ROOT / hooks.source_path(module)


def top_level_names(module: str) -> set[str]:
    """Names a module defines or imports at its top level."""
    tree = ast.parse(module_file(module).read_text(encoding="utf-8"))
    names: set[str] = set()
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            names.add(node.name)
        elif isinstance(node, ast.Assign):
            for target in node.targets:
                for leaf in ast.walk(target):
                    if isinstance(leaf, ast.Name):
                        names.add(leaf.id)
        elif isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
            names.add(node.target.id)
        elif isinstance(node, (ast.Import, ast.ImportFrom)):
            for alias in node.names:
                names.add((alias.asname or alias.name).split(".")[0])
        elif isinstance(node, (ast.If, ast.Try)):
            for sub in ast.walk(node):
                if isinstance(sub, (ast.FunctionDef, ast.ClassDef)):
                    names.add(sub.name)
                elif isinstance(sub, (ast.Import, ast.ImportFrom)):
                    for alias in sub.names:
                        names.add((alias.asname or alias.name).split(".")[0])
    return names


def resolves(target: str, modules: set[str]) -> bool:
    if target in modules:
        return True
    head, _, tail = target.rpartition(".")
    while head:
        if head in modules:
            first = tail.split(".")[0]
            return first in top_level_names(head)
        head, _, rest = head.rpartition(".")
        tail = f"{rest}.{tail}"
    return False


def main() -> int:
    problems: list[str] = []
    modules = hooks.discover_modules()
    module_set = set(modules)

    # 1. families and pages
    expected_pages: dict[str, str] = {}
    families: dict[str, list[str]] = {f: [] for f in hooks.FAMILIES}
    for module in modules:
        try:
            found = hooks.page_of(module)
        except ValueError as exc:
            problems.append(str(exc))
            continue
        if found is None:
            continue
        family, page = found
        families[family].append(module)
        expected_pages[page] = module
    for family in hooks.FAMILIES:
        index = API / family / "index.md"
        if not index.is_file():
            problems.append(f"{index.relative_to(ROOT)}: missing family index page")
    for page in sorted(API.rglob("*.md")):
        rel = page.relative_to(DOCS).as_posix()
        if page.name == "index.md":
            continue
        if rel not in expected_pages:
            problems.append(f"{rel}: a hand-written page for a module that does not exist")

    # 2. family pages name every module; 5. principal interfaces exist
    row = re.compile(r"^\|\s*\[`(plumetools(?:\.[\w]+)*)`\]\([^)]*\)\s*\|(.*)$")
    for family, members in families.items():
        index = API / family / "index.md"
        if not index.is_file():
            continue
        text = index.read_text(encoding="utf-8")
        for module in members:
            if module.count(".") == 1 and module.split(".")[1] == family:
                continue  # the package itself is rendered on this page
            if f"`{module}`" not in text:
                problems.append(f"{index.relative_to(ROOT)}: does not list {module}")
        for line in text.splitlines():
            match = row.match(line)
            if not match:
                continue
            module, rest = match.groups()
            if module not in module_set:
                problems.append(f"{index.relative_to(ROOT)}: lists {module}, which does not exist")
                continue
            cells = [c.strip() for c in rest.strip().strip("|").split("|")]
            if len(cells) < 2:
                continue
            defined = top_level_names(module)
            for name in re.findall(r"`([A-Za-z_][A-Za-z0-9_]*)`", cells[1]):
                if name not in defined:
                    problems.append(f"{index.relative_to(ROOT)}: {module} has no top-level name {name!r}")

    # 3. hand-written module pages render their module; 4. every ::: resolves
    directive = re.compile(r"^:::\s+([\w.]+)\s*$", re.M)
    for page in sorted(DOCS.rglob("*.md")):
        if "_tools" in page.parts:
            continue
        text = page.read_text(encoding="utf-8")
        targets = directive.findall(text)
        for target in targets:
            if not resolves(target, module_set):
                problems.append(f"{page.relative_to(ROOT)}: '::: {target}' does not resolve")
        rel = page.relative_to(DOCS).as_posix()
        if rel in expected_pages and expected_pages[rel] not in targets:
            problems.append(f"{rel}: hand-written page does not render {expected_pages[rel]}")

    n_pages = sum(len(v) for v in families.values())
    if problems:
        print(f"check_api: {len(problems)} problem(s)")
        for problem in problems:
            print(f"  {problem}")
        return 1
    print(f"check_api: {len(modules)} modules, {n_pages} module pages in "
          f"{len(families)} families; every family page lists its modules and "
          f"every documented name resolves")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
