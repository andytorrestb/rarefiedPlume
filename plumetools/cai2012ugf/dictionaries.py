def _vol_fields(name: str, sp: str, reset_until_s: float, t_ref: float,
                measure_mfp: bool, note: str) -> list[str]:
    return [
        f"    // {note}",
        "    field",
        "    {",
        "        fieldModel              uniGasVolFields;",
        "        timeProperties",
        "        {",
        "            sampleInterval              1;",
        "            resetAtOutput               on;",
        f"            resetAtOutputUntilTime      {_num(reset_until_s)};",
        "        }",
        "        uniGasVolFieldsProperties",
        "        {",
        f"            field                       {name};",
        f"            typeIds                     ({sp});",
        f"            measureMeanFreePath         {_bool(measure_mfp)};",
        f"            Tref                        {_num(t_ref)};",
        "            measureErrors               false;",
        "            averagingAcrossManyRuns     true;",
        "        }",
        "    }",
        "",
    ]


def render_field_properties_dict(cfg, run, settings) -> str:
    """``system/fieldPropertiesDict``: the running mean and the per-write window."""
    sp = _species(cfg)
    f = settings.fields
    lines = _header(
        "fieldPropertiesDict",
        "Two uniGasVolFields: a running mean from average_start_s (the dsmcFoam "
        "fieldAverage equivalent) and a per-write-interval average for "
        "Allconverge.py (spec §4-5).",
        "system")
    lines += ["uniGasFields", "("]
    lines += _vol_fields(
        f.mean_field, sp, run.average_start_s, cfg.gas.t_ref_K, True,
        "Reset at every write until average_start_s, then accumulated: the "
        "sampled mean. measureMeanFreePath writes the mean free path, sub-cell "
        "and time-step ratios the post-run verdict reads.")
    lines += _vol_fields(
        f.window_field, sp, 2.0 * run.end_time_s, cfg.gas.t_ref_K, False,
        "Reset at every write through the end: the average over each write "
        "interval, which stands in for dsmcFoam's single-step rhoN.")
    lines += [");"]
    return _text(lines)


