def _patch_boundary(patch: str, model: str, body: list[str]) -> list[str]:
    return [
        "    boundary",
        "    {",
        "        patchBoundaryProperties",
        "        {",
        f"            patch       {patch};",
        "        }",
        f"        boundaryModel   {model};",
        f"        {model}Properties",
        "        {",
        *[f"            {line}" for line in body],
        "        }",
        "    }",
        "",
    ]


def render_boundaries_dict(cfg, exit_state, settings) -> str:
    """``system/boundariesDict``: inject on the nozzle; delete everywhere open."""
    names = cfg.mesh.patch_names
    nozzle, upstream, outer = names["nozzle"], names["upstream_vacuum"], names["outer"]
    sp = _species(cfg)
    t0 = _num(exit_state.T0_K)
    lines = _header(
        "boundariesDict",
        "Cai's uniform drifting Maxwellian on the nozzle disk; every open patch "
        "deletes the particles that cross it.",
        "system")
    lines += ["uniGasPatchBoundaries", "("]
    for patch in (nozzle, upstream, outer):
        lines += _patch_boundary(patch, "uniGasDeletionPatch", ["allSpecies        yes;"])
    lines += [");", "", "uniGasGeneralBoundaries", "("]
    lines += [
        "    boundary",
        "    {",
        "        generalBoundaryProperties",
        "        {",
        f"            patch       {nozzle};",
        "        }",
        "        boundaryModel   uniGasFreeStreamInflowPatch;",
        "        uniGasFreeStreamInflowPatchProperties",
        "        {",
        f"            typeIds                     ({sp});",
        f"            numberDensities             {{{sp}    {_num(exit_state.number_density_per_m3)};}}",
        f"            translationalTemperature    {t0};",
        f"            rotationalTemperature       {t0};",
        f"            vibrationalTemperature      {t0};",
        f"            electronicTemperature       {t0};",
        f"            velocity                    {_axis_velocity(cfg, exit_state.velocity_m_per_s)};",
        "        }",
        "    }",
        ");",
        "",
        "uniGasCyclicBoundaries",
        "(",
        ");",
    ]
    return _text(lines)


