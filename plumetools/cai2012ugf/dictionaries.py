"""The uniGasFoam dictionaries of a cai2012-unigas case.

Everything physical comes from the case's ``case.yaml`` through the frozen
:mod:`plumetools.cai2012` derivation (exit state, particle weight, run window),
and everything solver-specific from its ``unigas.yaml``
(:mod:`plumetools.cai2012ugf.settings`). Layouts follow uniGasFoam's
``plumeImpingement`` tutorial and ``doc/GUIDE.md``.

Two ``controlDict`` variants are written, one per run leg (spec §6): the
startup leg to ``average_start_s`` writing once per domain transit, and the
sampling leg to ``end_time_s`` at the health cadence. ``system/controlDict``
starts as the startup copy; ``Allrun`` copies the leg it is about to run.
"""

from __future__ import annotations

from pathlib import Path

from plumetools.cai2012.dictionaries import render_decompose_par_dict
from plumetools.foamio.primitives import BANNER, SEPARATOR, write_lines

GENERATOR = "plumetools.cai2012ugf.dictionaries"

LEGS = ("startup", "sampling")


def _num(value: float) -> str:
    """A float at full precision, so every value round-trips."""
    return f"{float(value):.15g}"


def _bool(value: bool) -> str:
    return "true" if value else "false"


def _header(object_name: str, note: str, location: str) -> list[str]:
    return [
        BANNER,
        f"// GENERATED by {GENERATOR} from case.yaml and unigas.yaml -- do not edit.",
        "// Regenerate with ./Allmesh. Those two files are the authoritative source.",
        f"// {note}",
        "FoamFile",
        "{",
        "    version     2.0;",
        "    format      ascii;",
        "    class       dictionary;",
        f'    location    "{location}";',
        f"    object      {object_name};",
        "}",
        SEPARATOR,
        "",
    ]


def _text(lines: list[str]) -> str:
    lines = lines + ["", "// ************************************************************************* //"]
    return "\n".join(lines) + "\n"


def _species(cfg) -> str:
    return cfg.gas.species_name


def _axis_velocity(cfg, speed: float) -> str:
    axis = [float(c) for c in cfg.geometry.plume_axis]
    return "(" + " ".join(_num(speed * c) for c in axis) + ")"


