# --------------------------------------------------------------------------- #
# the case
# --------------------------------------------------------------------------- #

def write_case_dictionaries(case_dir: Path, cfg, exit_state, run, settings) -> list[Path]:
    """Write every uniGasFoam dictionary of a case; return the paths."""
    case_dir = Path(case_dir)
    system, constant = case_dir / "system", case_dir / "constant"
    startup = render_control_dict(cfg, run, settings, "startup")
    written = [
        write_lines(constant / "uniGasProperties",
                    render_uni_gas_properties(cfg, run, settings).splitlines()),
        write_lines(system / "boundariesDict",
                    render_boundaries_dict(cfg, exit_state, settings).splitlines()),
        write_lines(system / "fieldPropertiesDict",
                    render_field_properties_dict(cfg, run, settings).splitlines()),
        write_lines(system / "uniGasInitialisationDict",
                    render_initialisation_dict(cfg).splitlines()),
        write_lines(system / "hybridDecompositionDict",
                    render_hybrid_decomposition_dict(run, settings).splitlines()),
        write_lines(system / "chemReactDict", render_chem_react_dict().splitlines()),
        write_lines(system / "controlDict.startup", startup.splitlines()),
        write_lines(system / "controlDict.sampling",
                    render_control_dict(cfg, run, settings, "sampling").splitlines()),
        write_lines(system / "controlDict", startup.splitlines()),
        write_lines(system / "decomposeParDict",
                    render_decompose_par_dict(cfg).splitlines()),
        write_lines(system / "fvSchemes", render_fv_schemes().splitlines()),
        write_lines(system / "fvSolution", render_fv_solution().splitlines()),
    ]
    (case_dir / "0").mkdir(parents=True, exist_ok=True)
    return written
