"""Idempotent generation and validation of the cai2012-unigas family.

Built on the kn-extension's generation (:mod:`plumetools.cai2012ext.generation`)
-- staging, comparison, the create/keep/refresh/refuse decision, the manifest
-- with three differences:

* ``unigas.yaml`` is an **input**, like ``case.yaml``: a change to it is a
  conflict, so ``--refresh`` can never change the solver settings of a case
  that holds results (the frozen comparison would call it stale);
* ``case.yaml``'s ``meta`` and the manifest name this family and its solver;
* the dsmcFoam pre-run feasibility is recorded, not used: the production
  status is decided after the run (spec §7), so every case starts
  ``post-run-verdict-pending``.

:func:`validate` proves the inheritance: the template and study match the
kn-extension's, and every case's mesh dictionaries and particle weight are
those the kn-extension generates for the same Kn.
"""

from __future__ import annotations

import os
import re
import shutil
import tempfile
from pathlib import Path

import yaml

from plumetools.cai2012 import mesh as mesh_module
from plumetools.cai2012 import study as study_module
from plumetools.cai2012.config import load_case_config
from plumetools.cai2012.dictionaries import render_decompose_par_dict
from plumetools.cai2012.study import load_study
from plumetools.cai2012ext import direct_case
from plumetools.cai2012ext import generation as ext_generation
from plumetools.cai2012ext import policy as ext_policy
from plumetools.cai2012ext.provenance import git_provenance
from plumetools.cai2012ugf import policy
from plumetools.cai2012ugf.settings import UniGasConfigError, load_settings

GENERATOR = "plumetools.cai2012ugf.generation"
FAMILY_DIRECTORY = "cases/cai2012-unigas"
SOLVER = "uniGasFoam hybrid USP-DSMC"
STUDY_NAME = "Cai Knudsen sweep on uniGasFoam hybrid USP-DSMC"
PENDING = "post-run-verdict-pending"
INPUT_FILES = ("case.yaml", "unigas.yaml")
PILOT_DIR = "Pilot"
MESH_DICTIONARIES = ("blockMeshDict", "topoSetDict", "createPatchDict", "meshQualityDict")


class GenerationError(RuntimeError):
    """The family would not be the kn-extension's cases on another solver."""


# --------------------------------------------------------------------------- #
# staging
# --------------------------------------------------------------------------- #

def _meta(study) -> dict:
    meta = dict(study.meta or {})
    return {"unigas_commit": meta.get("unigas_commit"),
            "unigas_branch": meta.get("unigas_branch")}


def write_case_yaml(case_dir: Path, case, study) -> dict:
    """The kn-extension's ``case.yaml`` for this case, with this family's meta."""
    applied = ext_generation.write_case_yaml(case_dir, case, study)
    path = Path(case_dir) / "case.yaml"
    data = yaml.safe_load(path.read_text(encoding="utf-8"))
    data["meta"].update({
        "generated_by": GENERATOR,
        "family": FAMILY_DIRECTORY,
        "study": STUDY_NAME,
        "solver": SOLVER,
        **_meta(study),
    })
    header = (
        f"# GENERATED by {GENERATOR} -- do not edit.\n"
        "#\n"
        f"# {case.name}: Kn = {case.knudsen:g}. The kn-extension's case on "
        f"{SOLVER};\n"
        "# the solver settings are in unigas.yaml beside this file.\n"
        "#\n"
        "# Edit ../../baseCase/case.yaml, ../../baseCase/unigas.yaml or\n"
        "# ../../study.yaml and re-run ../../generate_cases.py. It never\n"
        "# overwrites a case with results.\n"
        "\n")
    path.write_text(header + yaml.safe_dump(data, sort_keys=False, default_flow_style=False),
                    encoding="utf-8", newline="\n")
    return applied


def stage(template: Path, staging_root: Path, case, study) -> Path:
    """Build one case in ``staging_root`` exactly as it would be generated."""
    destination = Path(staging_root) / case.name
    shutil.copytree(template, destination)
    study_module.prune_generated_dictionaries(destination)
    write_case_yaml(destination, case, study)
    load_settings(destination)
    return destination


def has_solver_output(case_dir: Path) -> bool:
    return (ext_generation.has_solver_output(case_dir)
            or (Path(case_dir) / "log.uniGasFoam").is_file())


def classify(root: Path, study, staging_root: Path, cases: list) -> list:
    """Stage every case and say what it is relative to the disk."""
    template = Path(root) / study.base_case
    states = []
    for case in cases:
        destination = Path(root) / study.case_path(case)
        staged = stage(template, staging_root, case, study)
        limits = staged / "KNOWN-LIMITATIONS"
        known = limits.read_text(encoding="utf-8") if limits.is_file() else ""
        if not destination.exists():
            state = ext_generation.CaseState(case, destination, staged,
                                             ext_generation.STATUS_NEW)
            state.known_limitations = known
            states.append(state)
            continue
        inputs, auxiliary = ext_generation.compare(staged, destination)
        promoted = [a for a in auxiliary if a.startswith("unigas.yaml:")]
        inputs = inputs + promoted
        auxiliary = [a for a in auxiliary if a not in promoted]
        if inputs:
            status = ext_generation.STATUS_CONFLICT
        elif auxiliary:
            status = ext_generation.STATUS_STALE
        else:
            status = ext_generation.STATUS_IDENTICAL
        state = ext_generation.CaseState(
            case, destination, staged, status, has_results=has_solver_output(destination),
            inputs=inputs, auxiliary=auxiliary)
        state.known_limitations = known
        states.append(state)
    return states


# --------------------------------------------------------------------------- #
# checks against the kn-extension
# --------------------------------------------------------------------------- #

def inheritance_problems(root: Path, study=None) -> list[str]:
    """Template and study differences from the kn-extension, as messages."""
    root = Path(root)
    study = study or load_study(root / "study.yaml")
    ext = policy.kn_extension_root()
    problems = [f"baseCase/case.yaml: {key} differs from the kn-extension"
                for key in policy.template_differences(
                    load_case_config(root / study.base_case),
                    load_case_config(ext / "baseCase"))]
    problems += [f"study.yaml: {p}" for p in policy.study_differences(
        study, load_study(ext / "study.yaml"))]
    return problems


