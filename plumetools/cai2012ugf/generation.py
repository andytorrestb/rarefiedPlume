def _mesh_files(cfg, workdir: Path) -> dict:
    case = direct_case.derive_config(cfg)
    workdir.mkdir(parents=True, exist_ok=True)
    mesh_module.write_mesh_setup(workdir, case.cfg, case.geom, case.plan)
    files = {name: (workdir / "system" / name).read_bytes() for name in MESH_DICTIONARIES}
    files["decomposeParDict"] = render_decompose_par_dict(case.cfg).encode("utf-8")
    return files, case.run.n_equivalent_particles


def validate(family_root: Path) -> list[str]:
    """Every way the generated family departs from the kn-extension; empty passes."""
    root = Path(family_root).resolve()
    study = load_study(root / "study.yaml")
    problems = inheritance_problems(root, study) + copy_differences(root)
    ext_root = policy.kn_extension_root()
    ext_study = load_study(ext_root / "study.yaml")
    ext_cases = {c.name: c for c in ext_study.expand()}
    with tempfile.TemporaryDirectory() as scratch:
        scratch = Path(scratch)
        for case in study.expand():
            case_dir = root / study.case_path(case)
            if not case_dir.is_dir():
                problems.append(f"{case.name}: not generated")
                continue
            try:
                load_settings(case_dir)
            except UniGasConfigError as exc:
                problems.append(f"{case.name}: {exc}")
            if case.name not in ext_cases:
                problems.append(f"{case.name}: no kn-extension case of that name")
                continue
            ext_dir = ext_generation.stage(ext_root / ext_study.base_case,
                                           scratch / "ext", ext_cases[case.name], ext_study)
            problems += [f"{case.name}: case.yaml {key} differs from the kn-extension's case"
                         for key in policy.template_differences(load_case_config(case_dir),
                                                                load_case_config(ext_dir))]
            mine, my_weight = _mesh_files(load_case_config(case_dir), scratch / "mine" / case.name)
            theirs, their_weight = _mesh_files(load_case_config(ext_dir),
                                               scratch / "theirs" / case.name)
            for name in mine:
                if mine[name] != theirs[name]:
                    problems.append(f"{case.name}: system/{name} differs from the kn-extension's")
            if abs(my_weight - their_weight) > 1e-12 * abs(their_weight):
                problems.append(f"{case.name}: nEquivalentParticles {my_weight:.17g} vs "
                                f"kn-extension {their_weight:.17g}")
    return problems


