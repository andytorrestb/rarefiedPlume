# the manifest
# --------------------------------------------------------------------------- #

def _criterion(assessment: dict, name: str):
    for criterion in assessment.get("criteria") or []:
        if isinstance(criterion, dict) and criterion.get("name") == name:
            return criterion
    return None


def build_entry(root: Path, study, study_path: Path, case, case_dir: Path) -> tuple[dict, list]:
    """The kn-extension's manifest row, relabelled for this family."""
    entry, lines = ext_generation.build_entry(root, study, study_path, case, case_dir)
    assessment = entry.pop("feasibility")
    entry["dsmcfoam_prerun_feasibility"] = assessment
    entry["dsmcfoam_prerun_status"] = entry["production_status"]
    entry["production_status"] = PENDING
    entry["solver"] = SOLVER
    entry.update(_meta(study))
    entry["prerun_gates"] = {
        "hard_dsmc_check_failures": int(entry["dsmc_checks"]["n_failures"]),
        "mesh_budget": _criterion(assessment, "mesh_budget"),
        "estimated_parcels": (assessment.get("cost") or {}).get("estimated_parcels"),
    }
    entry["unigas_settings"] = yaml.safe_load(
        (Path(case_dir) / "unigas.yaml").read_text(encoding="utf-8"))
    return entry, lines


def write_manifest(path: Path, study, entries: list, *, study_path: Path, strays: list) -> Path:
    """The kn-extension's manifest, then relabelled for this family."""
    path = Path(path)
    ext_generation.write_manifest(
        path, study, entries, study_path=study_path,
        inheritance={"source": str(policy.KN_EXTENSION / "baseCase" / "case.yaml"),
                     "rule": "identical outside meta (validate_cases.py)",
                     "problems": inheritance_problems(path.parent, study)},
        code=git_provenance(policy.repo_root()), strays=strays)
    document = yaml.safe_load(path.read_text(encoding="utf-8"))
    document.update({"study": STUDY_NAME, "generator": GENERATOR,
                     "family": FAMILY_DIRECTORY, "solver": SOLVER, **_meta(study)})
    text = (f"# GENERATED by {GENERATOR} -- do not edit.\n"
            "# The auditable map from case name to inputs, provenance and status.\n"
            "# production_status is decided after each run (spec §7).\n\n"
            + yaml.safe_dump(document, sort_keys=False, default_flow_style=False))
    scratch = path.with_name(path.name + ".tmp")
    scratch.write_text(text, encoding="utf-8", newline="\n")
    os.replace(scratch, path)
    return path


