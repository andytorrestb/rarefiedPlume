# generate
# --------------------------------------------------------------------------- #

def _load(family_root: Path):
    root = Path(family_root).resolve()
    study_path = root / "study.yaml"
    study = load_study(study_path)
    ext_policy.check_study(study)
    problems = inheritance_problems(root, study)
    if problems:
        raise GenerationError(
            "the family no longer matches the kn-extension:\n    " + "\n    ".join(problems))
    return root, study_path, study


def generate(family_root: Path, *, dry_run: bool = False, refresh: bool = False,
             regenerate: bool = False, overwrite: bool = False) -> list:
    """Stage, compare and (unless refused or ``dry_run``) apply; write the manifest.

    Returns the per-case states. Nothing is applied and the manifest is not
    written when any case is refused.
    """
    root, study_path, study = _load(family_root)
    cases = study.expand()
    with tempfile.TemporaryDirectory(dir=root, prefix=".staging-") as scratch:
        states = classify(root, study, Path(scratch), cases)
        ext_generation.decide(states, refresh=refresh, regenerate=regenerate,
                              overwrite=overwrite)
        if dry_run or any(s.blocking for s in states):
            return states
        for state in states:
            for target in (state.destination, state.staged):
                if not Path(target).resolve().is_relative_to(root):
                    raise GenerationError(f"generation target escaped {root}: {target}")
        ext_generation.apply(states)
    entries = [build_entry(root, study, study_path, case, root / study.case_path(case))[0]
               for case in cases]
    write_manifest(root / study.manifest_name, study, entries, study_path=study_path,
                   strays=ext_generation.stray_directories(root, study, cases))
    return states


def stage_pilot(family_root: Path, kn_name: str) -> Path:
    """Stage one Kn case under ``Pilot/`` with a ``PILOT`` marker; never in the manifest."""
    root, _, study = _load(family_root)
    matches = [c for c in study.expand() if c.knudsen_case.name == kn_name]
    if not matches:
        raise GenerationError(f"no case named {kn_name} in {root / 'study.yaml'}")
    case = matches[0]
    destination = root / PILOT_DIR / case.name
    if destination.exists():
        if has_solver_output(destination):
            raise GenerationError(f"{destination} holds solver output; remove it by hand "
                                  f"to stage a fresh pilot")
        shutil.rmtree(destination)
    destination.parent.mkdir(parents=True, exist_ok=True)
    stage(root / study.base_case, destination.parent, case, study)
    (destination / "PILOT").write_text(
        f"PILOT: {case.name} at Kn = {case.knudsen:g}, outside the manifest. Its results\n"
        "measure cost and resolution (spec §8); they are never production results.\n",
        encoding="utf-8")
    return destination


