"""uniGasFoam against dsmcFoam at Kn = 0.1 and 1 (spec §9).

Both families' ``Allcompare.py`` write ``results/comparison.yaml`` with the
same estimators on the same meshes and particle weight. This puts every numeric
metric side by side with its difference. There is no tolerance: differences are
reported, as everywhere in this repository. At Kn >= 0.1 uniGasFoam is in
effect DSMC throughout, so the remaining numerical difference is the time step,
named in the report.

    python -m plumetools.cai2012ugf.crosscheck

writes ``cases/cai2012-unigas/results/crosscheck.{yaml,md}``.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import yaml

DEFAULT_CASES = ("Kn0p1_np1x", "Kn1_np1x")
NUMERICS = ("uniGasFoam: adaptive time step, Co 0.5 on max(u, v0) and 0.2 tau in DSMC "
            "cells; dsmcFoam: fixed time step at Co 0.2 on U0 + 3 sigma. Same meshes, same "
            "particle weight, same run window and estimators.")


def _cases_dir(root: Path) -> str:
    document = yaml.safe_load((Path(root) / "study.yaml").read_text(encoding="utf-8")) or {}
    return str(document.get("cases_dir") or "Cases")


def _flatten(data, prefix: str = "") -> dict:
    flat = {}
    if isinstance(data, dict):
        for key, value in data.items():
            flat.update(_flatten(value, f"{prefix}{key}."))
    elif isinstance(data, (int, float)) and not isinstance(data, bool):
        flat[prefix[:-1]] = float(data)
    return flat


def _metrics(root: Path, case: str):
    path = Path(root) / _cases_dir(root) / case / "results" / "comparison.yaml"
    if not path.is_file():
        return None
    return _flatten(yaml.safe_load(path.read_text(encoding="utf-8")) or {})


def report(ugf_root: Path, dsmc_root: Path, cases=DEFAULT_CASES) -> dict:
    """Pair the two families' comparison metrics; write the report files."""
    ugf_root, dsmc_root = Path(ugf_root), Path(dsmc_root)
    doc = {"numerics": NUMERICS, "tolerance": None, "cases": {}}
    for case in cases:
        mine, theirs = _metrics(ugf_root, case), _metrics(dsmc_root, case)
        missing = [name for name, m in (("uniGasFoam", mine), ("dsmcFoam", theirs)) if m is None]
        entry = {"missing": missing, "metrics": {}}
        if not missing:
            for key in sorted(set(mine) & set(theirs)):
                entry["metrics"][key] = {"dsmcFoam": theirs[key], "uniGasFoam": mine[key],
                                         "difference": mine[key] - theirs[key]}
        doc["cases"][case] = entry
    results = ugf_root / "results"
    results.mkdir(parents=True, exist_ok=True)
    (results / "crosscheck.yaml").write_text(
        "# GENERATED by plumetools.cai2012ugf.crosscheck -- no tolerance; not validated.\n"
        + yaml.safe_dump(doc, sort_keys=False), encoding="utf-8")
    lines = ["# uniGasFoam against dsmcFoam", "",
             "Same meshes, weight, window and estimators. Differences are reported with no "
             "tolerance. Not validated.", "", f"Numerics: {NUMERICS}", ""]
    for case, entry in doc["cases"].items():
        lines += [f"## {case}", ""]
        if entry["missing"]:
            lines += [f"Missing results: {', '.join(entry['missing'])}.", ""]
            continue
        lines += ["| metric | dsmcFoam | uniGasFoam | difference |", "|---|---:|---:|---:|"]
        for key, row in entry["metrics"].items():
            lines.append(f"| {key} | {row['dsmcFoam']:.6g} | {row['uniGasFoam']:.6g} | "
                         f"{row['difference']:.3g} |")
        lines.append("")
    (results / "crosscheck.md").write_text("\n".join(lines), encoding="utf-8")
    return doc


def main(argv=None) -> int:
    repo = Path(__file__).resolve().parents[2]
    parser = argparse.ArgumentParser(prog="python -m plumetools.cai2012ugf.crosscheck")
    parser.add_argument("--unigas", type=Path, default=repo / "cases" / "cai2012-unigas")
    parser.add_argument("--dsmc", type=Path, default=repo / "cases" / "cai2012-kn-extension")
    parser.add_argument("--case", action="append", dest="cases")
    args = parser.parse_args(argv)
    doc = report(args.unigas, args.dsmc, tuple(args.cases or DEFAULT_CASES))
    for case, entry in doc["cases"].items():
        print(f"  {case}: " + (f"missing {', '.join(entry['missing'])}" if entry["missing"]
                               else f"{len(entry['metrics'])} metrics paired"))
    print(f"  {Path(args.unigas) / 'results' / 'crosscheck.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
