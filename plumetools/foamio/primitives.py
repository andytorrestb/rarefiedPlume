@dataclass(frozen=True)
class SearchableSurface:
    """Base for the analytic surfaces snappyHexMesh can snap to.

    Attributes:
        name: the ``geometry`` entry name. snappyHexMesh names the patch it
            creates after this, so it *is* the patch name -- there is no separate
            place to set it.
        level: octree refinement level at this surface. The resulting cell size is
            ``background_cell_size / 2**level``.
        patch_type: the geometric type of the created patch, written into
            ``patchInfo``. This is load-bearing for DSMC:

            * ``patch`` -- particles crossing it are **deleted**
              (``particle::hitBoundaryFace`` falls through to
              ``td.keepParticle = false``). Correct for an inflow surface and for
              an open vacuum boundary.
            * ``wall`` -- ``DSMCParcel::hitWallPatch`` runs, which both records the
              surface fluxes (``fD``, ``q``, ``rhoN``...) and applies the
              ``WallInteractionModel``. Required for a solid body: a body declared
              as ``patch`` would absorb every particle that hit it and exert no
              force.
    """

    name: str
    level: int = 0
    patch_type: str = "patch"

    def geometry_lines(self) -> list[str]:
        """The body of this surface's ``geometry`` entry, indented four spaces."""
        raise NotImplementedError

    def validate(self) -> None:
        """Raise ``ValueError`` if the surface is degenerate."""
        if int(self.level) < 0:
            raise ValueError(
                f"{self.name}: refinement level must be >= 0, got {self.level}")

    def min_feature_size_m(self) -> float:
        """The thinnest dimension of the body [m].

        What the **refined** cell has to resolve: for a plate this is the
        thickness, and cells no smaller than it cannot represent the body as a
        solid with two distinct faces.
        """
        raise NotImplementedError

    def max_feature_size_m(self) -> float:
        """The largest dimension of the body [m].

        What the **background** cell has to be smaller than. A body smaller than
        one background cell in every direction can sit entirely inside that cell,
        never intersect a cell boundary, and so never get flagged for refinement.
        """
        raise NotImplementedError

    def refined_cell_size_m(self, background_cell_size_m: float) -> float:
        """Cell size at this surface [m]: the background halved once per level."""
        return float(background_cell_size_m) / 2 ** int(self.level)


@dataclass(frozen=True)
class SearchableSphere(SearchableSurface):
    """An analytic sphere.

    Attributes:
        centre: ``(x, y, z)`` [m].
        radius: [m].

    v1706 spells the key ``centre``; v2006+ accepts ``origin`` as well, so
    ``centre`` is written for the wider compatibility.
    """

    centre: tuple = (0.0, 0.0, 0.0)
    radius: float = 1.0

    def geometry_lines(self) -> list[str]:
        return [
            "        type    searchableSphere;",
            f"        centre  {fmt_point(self.centre)};",
            f"        radius  {fmt(self.radius)};",
        ]

    def validate(self) -> None:
        super().validate()
        if not self.radius > 0.0:
            raise ValueError(f"{self.name}: sphere radius must be positive, "
                             f"got {self.radius}")

    def min_feature_size_m(self) -> float:
        return float(self.radius)

    def max_feature_size_m(self) -> float:
        return 2.0 * float(self.radius)


@dataclass(frozen=True)
class SearchableCylinder(SearchableSurface):
    """An analytic finite cylinder, capped at both ends.

    Attributes:
        point1: centre of one end cap [m].
        point2: centre of the other end cap [m].
        radius: [m].

    Finite and capped is the point: the paper's cylinder has ends inside the
    domain, and a cylinder that ran to the boundary would remove the
    three-dimensional wake around them.
    """

    point1: tuple = (0.0, 0.0, 0.0)
    point2: tuple = (0.0, 0.0, 1.0)
    radius: float = 1.0

    def geometry_lines(self) -> list[str]:
        return [
            "        type    searchableCylinder;",
            f"        point1  {fmt_point(self.point1)};",
            f"        point2  {fmt_point(self.point2)};",
            f"        radius  {fmt(self.radius)};",
        ]

    def validate(self) -> None:
        super().validate()
        if not self.radius > 0.0:
            raise ValueError(f"{self.name}: cylinder radius must be positive, "
                             f"got {self.radius}")
        if self.length_m() <= 0.0:
            raise ValueError(f"{self.name}: cylinder end caps coincide")

    def length_m(self) -> float:
        """Distance between the two end-cap centres [m]."""
        return sum((b - a) ** 2 for a, b in zip(self.point1, self.point2)) ** 0.5

    def min_feature_size_m(self) -> float:
        return min(float(self.radius), self.length_m())

    def max_feature_size_m(self) -> float:
        return max(2.0 * float(self.radius), self.length_m())


@dataclass(frozen=True)
class SearchableBox(SearchableSurface):
    """An analytic axis-aligned box.

    Attributes:
        min: ``(x, y, z)`` of the low corner [m].
        max: ``(x, y, z)`` of the high corner [m].

    Used here for the flat plate. Its thinnest dimension is what
    :meth:`min_feature_size_m` reports, which for a plate is the thickness -- the
    dimension a background mesh is most likely to be unable to find.
    """

    min: tuple = (0.0, 0.0, 0.0)
    max: tuple = (1.0, 1.0, 1.0)

    def geometry_lines(self) -> list[str]:
        return [
            "        type    searchableBox;",
            f"        min     {fmt_point(self.min)};",
            f"        max     {fmt_point(self.max)};",
        ]

    def validate(self) -> None:
        super().validate()
        for axis, (lo, hi) in enumerate(zip(self.min, self.max)):
            if not hi > lo:
                raise ValueError(
                    f"{self.name}: box axis {'xyz'[axis]} is degenerate "
                    f"({lo} .. {hi}); a zero-thickness body cannot be meshed as a "
                    f"solid, and snappyHexMesh has no baffle mode configured here")

    def min_feature_size_m(self) -> float:
        return min(hi - lo for lo, hi in zip(self.min, self.max))

    def max_feature_size_m(self) -> float:
        return max(hi - lo for lo, hi in zip(self.min, self.max))


