r"""Reusable pieces of a blockMesh + snappyHexMesh setup.

Two case families in this repository build a mesh the same way: a plain Cartesian
box from ``blockMesh``, then ``snappyHexMesh`` carving analytic **searchable
primitives** out of it. :mod:`plumetools.foamio.snappy` does it for a single
hemispherical inflow cavity; :mod:`plumetools.markelov1999.mesh` does it for an
inflow hemisphere plus a cylinder and a plate.

The differences between them are the surface list, the patch layout and the
refinement levels -- not the dictionary syntax. So the syntax lives here once and
both compose it, rather than each carrying its own copy of the castellate/snap
boilerplate.

Why primitives rather than STL
------------------------------
A ``searchableSphere`` / ``searchableCylinder`` / ``searchableBox`` is analytic:
snappyHexMesh snaps to the true surface instead of to a triangulation of it, the
worst measured vertex deviation on the existing case is 8.3e-16 m (round-off),
and nothing outside the repository has to be generated, versioned or shipped. An
STL would give up all three.

Block ordering
--------------
:func:`render_box_block_mesh_dict` emits the canonical OpenFOAM box ordering, in
which the block's local axes are ``(x, y, z)`` in that order, so a
``(nx ny nz)`` division triple means what it reads as.

That is worth stating because the ordering this module replaced did **not** have
that property: its local ``x1`` ran along ``+y`` and its ``x3`` along ``+x``, so
the three division counts were applied to the wrong axes. It went unnoticed
because the only case using it has a cube-shaped domain with all three counts
equal. On a non-cubic domain it would have silently transposed the resolution.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

BANNER = """\
/*--------------------------------*- C++ -*----------------------------------*\\
| =========                 |                                                 |
| \\\\      /  F ield         | OpenFOAM: The Open Source CFD Toolbox           |
|  \\\\    /   O peration     | Version:  v1706                                 |
|   \\\\  /    A nd           | Web:      www.OpenFOAM.com                      |
|    \\\\/     M anipulation  |                                                 |
\\*---------------------------------------------------------------------------*/"""

SEPARATOR = "// * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * //"

#: Face keys accepted by :func:`render_box_block_mesh_dict`, and the vertex
#: quadruple of each in the canonical ordering below. Wound so the normal points
#: out of the box, which is what OpenFOAM requires of a boundary face.
BOX_FACES = {
    "x_min": (0, 4, 7, 3),
    "x_max": (1, 2, 6, 5),
    "y_min": (0, 1, 5, 4),
    "y_max": (3, 7, 6, 2),
    "z_min": (0, 3, 2, 1),
    "z_max": (4, 5, 6, 7),
}


def fmt(value: float) -> str:
    """Format a length for an OpenFOAM dictionary: 10 significant figures.

    Enough that a 0.1 mm feature in a 1 m domain survives the round trip, short
    enough that the dictionaries stay readable.
    """
    return f"{value:.10g}"


def fmt_point(point) -> str:
    """Format an ``(x, y, z)`` triple as an OpenFOAM vector literal."""
    x, y, z = point
    return f"({fmt(x)} {fmt(y)} {fmt(z)})"


def header(object_name: str, generator: str, note: str) -> list[str]:
    """The ``FoamFile`` block, plus a provenance comment naming the generator.

    Args:
        object_name: the ``object`` entry, which must match the file name.
        generator: dotted module path that wrote the file, so a reader of a
            generated dictionary can find the code that produced it.
        note: one line describing what this particular dictionary does.
    """
    return [
        BANNER,
        f"// GENERATED by {generator} from case.yaml -- do not edit.",
        "// Regenerate with ./Allmesh.",
        f"// {note}",
        "FoamFile",
        "{",
        "    version     2.0;",
        "    format      ascii;",
        "    class       dictionary;",
        f"    object      {object_name};",
        "}",
        SEPARATOR,
        "",
    ]


def write_lines(path: Path, lines: list[str]) -> Path:
    """Write LF-terminated lines, creating the parent directory.

    ``newline="\\n"`` explicitly: OpenFOAM reads CRLF, but a dictionary whose line
    endings depend on which platform generated it makes every diff unreadable.
    """
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    return path


