def render_geometry_block(surfaces) -> list[str]:
    """The ``geometry { ... }`` block for a list of searchable surfaces.

    Raises:
        ValueError: for a duplicate surface name -- which would silently drop one
            of them, since OpenFOAM dictionary keys are unique.
    """
    names = [s.name for s in surfaces]
    duplicates = sorted({n for n in names if names.count(n) > 1})
    if duplicates:
        raise ValueError(f"duplicate searchable surface name(s) {duplicates}")

    lines = ["geometry", "{"]
    for surface in surfaces:
        surface.validate()
        lines += [f"    {surface.name}", "    {", *surface.geometry_lines(), "    }"]
    lines.append("}")
    return lines


def render_refinement_surfaces_block(surfaces, indent: str = "    ") -> list[str]:
    """The ``refinementSurfaces { ... }`` block, one entry per surface."""
    lines = [f"{indent}refinementSurfaces", f"{indent}{{"]
    for surface in surfaces:
        level = int(surface.level)
        lines += [
            f"{indent}    {surface.name}",
            f"{indent}    {{",
            f"{indent}        level ({level} {level});",
            f"{indent}        patchInfo",
            f"{indent}        {{",
            f"{indent}            type {surface.patch_type};",
            f"{indent}        }}",
            f"{indent}    }}",
        ]
    lines += [f"{indent}}}"]
    return lines


#: Cells required across the thinnest dimension of a body for it to be meshed as
#: a solid rather than as a smeared obstruction.
MIN_CELLS_ACROSS_THINNEST_FEATURE = 2


def check_surfaces_are_resolvable(surfaces, background_cell_size_m: float) -> None:
    """Refuse a background and level combination that cannot mesh a surface.

    Args:
        surfaces: the searchable surfaces, each carrying its own ``level``.
        background_cell_size_m: the uniform background cell size [m].

    Raises:
        ValueError: naming the surface, the offending dimension and the level that
            would fix it.

    Two separate conditions, for two separate failure modes:

    **Finding it.** snappyHexMesh only refines cells that intersect a surface, so
    a body smaller than one background cell in *every* direction can sit entirely
    inside that cell and never be flagged. The background cell must therefore be
    smaller than the body's largest dimension. Note this is not the same as being
    smaller than its *smallest*: a plate 12.7 mm thick and 381 mm tall spans
    hundreds of background cells laterally and cannot be missed, however coarse
    the background is relative to its thickness.

    **Resolving it.** After refinement the cell size is
    ``background / 2**level``, and that has to fit across the body's thinnest
    dimension at least :data:`MIN_CELLS_ACROSS_THINNEST_FEATURE` times. Below
    that, a plate has no interior for snappyHexMesh to remove and comes out as a
    dented single layer of cells rather than as a body with two faces.
    """
    if background_cell_size_m <= 0.0:
        raise ValueError(
            f"background cell size must be positive, got {background_cell_size_m}")

    import math

    for surface in surfaces:
        largest = surface.max_feature_size_m()
        if background_cell_size_m >= largest:
            raise ValueError(
                f"background_cell_size_m ({background_cell_size_m}) is not smaller "
                f"than the largest dimension of surface {surface.name!r} "
                f"({largest:.6g} m), so the whole body can sit inside one background "
                f"cell and never be found. Reduce the background cell size."
            )

        smallest = surface.min_feature_size_m()
        refined = surface.refined_cell_size_m(background_cell_size_m)
        needed = smallest / MIN_CELLS_ACROSS_THINNEST_FEATURE
        if refined > needed:
            required_level = math.ceil(math.log2(background_cell_size_m / needed))
            raise ValueError(
                f"surface {surface.name!r} at refinement level {surface.level} gives "
                f"cells of {refined:.6g} m, but its thinnest dimension is "
                f"{smallest:.6g} m -- only {smallest / refined:.2f} cells across, "
                f"against the {MIN_CELLS_ACROSS_THINNEST_FEATURE} needed to mesh it "
                f"as a solid. Raise its refinement level to {required_level}, or "
                f"reduce background_cell_size_m."
            )


def render_snap_controls() -> list[str]:
    """``snapControls``, tuned for analytic primitives with no feature edges.

    Feature snapping is off. The primitives here have no feature edges to capture
    except where a surface meets a domain boundary, and explicit feature snapping
    tends to pull points *off* such a surface rather than onto it. The one place
    it would matter -- the rim where the inflow hemisphere crosses ``x = 0`` -- is
    a right-angle crossing, the well-conditioned case.
    """
    return [
        "snapControls",
        "{",
        "    nSmoothPatch    3;",
        "    tolerance       2.0;",
        "    nSolveIter      50;",
        "    nRelaxIter      5;",
        "    nFeatureSnapIter        10;",
        "    implicitFeatureSnap     false;",
        "    explicitFeatureSnap     false;",
        "    multiRegionFeatureSnap  false;",
        "}",
    ]


def render_add_layers_controls() -> list[str]:
    """``addLayersControls``. Present but inert -- DSMC needs no prism layers.

    A DSMC wall interaction is a discrete particle-surface collision, not a
    resolved viscous sublayer, so there is nothing for a layer stack to resolve.
    The block is still written because snappyHexMesh requires the entry even when
    ``addLayers`` is false.
    """
    return [
        "addLayersControls",
        "{",
        "    relativeSizes       true;",
        "    layers {}",
        "    expansionRatio      1.0;",
        "    finalLayerThickness 0.3;",
        "    minThickness        0.1;",
        "    nGrow               0;",
        "    featureAngle        60;",
        "    nRelaxIter          3;",
        "    nSmoothSurfaceNormals 1;",
        "    nSmoothNormals      3;",
        "    nSmoothThickness    10;",
        "    maxFaceThicknessRatio 0.5;",
        "    maxThicknessToMedialRatio 0.3;",
        "    minMedialAxisAngle  90;",
        "    nBufferCellsNoExtrude 0;",
        "    nLayerIter          50;",
        "}",
    ]


def render_snappy_dict(surfaces, *, location_in_mesh, n_cells_between_levels: int,
                       generator: str, note: str, preamble: list[str] | None = None,
                       max_global_cells: int = 20_000_000,
                       resolve_feature_angle: int = 30) -> str:
    """A complete ``snappyHexMeshDict`` for a list of searchable surfaces.

    Args:
        surfaces: the :class:`SearchableSurface` entries to carve. Each becomes
            both a ``geometry`` entry and a ``refinementSurfaces`` entry, and
            snappyHexMesh names the patch it creates after the entry.
        location_in_mesh: ``(x, y, z)`` seed point [m], which must be in the fluid.
        n_cells_between_levels: buffer cells between refinement levels.
        generator: dotted module path, for the provenance comment.
        note: one line describing the mesh.
        preamble: extra comment lines placed before the ``geometry`` block.
        max_global_cells: castellation cell ceiling. Deliberately generous: an
            octree that hits this limit stops refining and produces a *quietly
            under-resolved* mesh rather than an error, so the ceiling should be a
            backstop against a runaway configuration, not a budget.
        resolve_feature_angle: castellation feature angle [deg].

    Returns:
        The dictionary text.

    Raises:
        ValueError: for ``n_cells_between_levels < 0``, or from
            :func:`render_geometry_block` for a duplicate or degenerate surface.

    Layer addition is off. A DSMC wall interaction is a discrete particle-surface
    collision, so there is no viscous sublayer for a prism stack to resolve, and
    the highly non-orthogonal cells a layer stack produces would only hurt.
    """
    if int(n_cells_between_levels) < 0:
        raise ValueError(
            f"n_cells_between_levels must be >= 0, got {n_cells_between_levels}")

    lines = header("snappyHexMeshDict", generator, note)
    lines += [
        "castellatedMesh true;",
        "snap            true;",
        "addLayers       false;   // DSMC: no boundary-layer stack needed",
        "",
    ]
    lines += list(preamble or [])
    lines += render_geometry_block(surfaces)
    lines += [
        "",
        "castellatedMeshControls",
        "{",
        f"    maxLocalCells       {max_global_cells // 2};",
        f"    maxGlobalCells      {max_global_cells};",
        "    minRefinementCells  10;",
        "    maxLoadUnbalance    0.10;",
        f"    nCellsBetweenLevels {int(n_cells_between_levels)};",
        "",
        "    // No feature edges: an analytic sphere, cylinder or box exposes none",
        "    // that snappyHexMesh can extract without a surfaceFeatures pass.",
        "    features ();",
        "",
    ]
    lines += render_refinement_surfaces_block(surfaces, indent="    ")
    lines += [
        "",
        f"    resolveFeatureAngle {int(resolve_feature_angle)};",
        "",
        "    // No wake, shock or gap refinement regions yet -- deliberately. This",
        "    // block is the clean place to add them.",
        "    refinementRegions",
        "    {",
        "    }",
        "",
        "    // In the fluid: inside the box, outside every carved body, and off",
        "    // every symmetry plane. snappyHexMesh keeps the region connected to",
        "    // this point and discards everything else.",
        f"    locationInMesh {fmt_point(location_in_mesh)};",
        "",
        "    allowFreeStandingZoneFaces true;",
        "}",
        "",
    ]
    lines += render_snap_controls()
    lines += [""]
    lines += render_add_layers_controls()
    lines += [
        "",
        "meshQualityControls",
        "{",
        '    #include "meshQualityDict"',
        "}",
        "",
        "debug 0;",
        "mergeTolerance 1e-6;",
        "",
        "// ************************************************************************* //",
    ]
    return "\n".join(lines) + "\n"


def render_mesh_quality_dict(generator: str) -> str:
    """``meshQualityDict``, ``#include``d by ``snappyHexMeshDict``.

    Kept as a local file rather than including OpenFOAM's own
    ``etc/caseDicts/meshQualityDict`` so a case does not depend on an installation
    path that varies between distributions and versions.
    """
    lines = header("meshQualityDict", generator, "Quality limits for snappyHexMesh.")
    lines += [
        "maxNonOrtho         65;",
        "maxBoundarySkewness 20;",
        "maxInternalSkewness  4;",
        "maxConcave          80;",
        "minVol              1e-13;",
        "minTetQuality       1e-30;",
        "minArea             -1;",
        "minTwist            0.02;",
        "minDeterminant      0.001;",
        "minFaceWeight       0.02;",
        "minVolRatio         0.01;",
        "minTriangleTwist    -1;",
        "",
        "nSmoothScale 4;",
        "errorReduction 0.75;",
        "",
        "relaxed",
        "{",
        "    maxNonOrtho 75;",
        "}",
        "",
        "// ************************************************************************* //",
    ]
    return "\n".join(lines) + "\n"


