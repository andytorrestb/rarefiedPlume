@dataclass(frozen=True)
class BoxPatch:
    """One boundary patch of the background box.

    Attributes:
        name: patch name.
        type: OpenFOAM geometric type -- ``patch``, ``wall`` or ``symmetry``.
        faces: which box faces belong to it; keys of :data:`BOX_FACES`.
        comment: appended to the patch entry, for a reader of the dictionary.
    """

    name: str
    type: str
    faces: tuple
    comment: str = ""


def render_box_block_mesh_dict(bounds, divisions, patches, *, generator: str,
                               note: str) -> str:
    """A plain uniform hexahedral box, with named boundary patches.

    Args:
        bounds: ``(x_min, x_max, y_min, y_max, z_min, z_max)`` [m].
        divisions: ``(nx, ny, nz)`` cell counts along ``x``, ``y`` and ``z``.
        patches: :class:`BoxPatch` entries. Every face in :data:`BOX_FACES` must
            be claimed exactly once.
        generator: dotted module path, for the provenance comment.
        note: one line describing the mesh.

    Returns:
        The dictionary text.

    Raises:
        ValueError: for inverted bounds, non-positive divisions, an unknown face
            key, or a face claimed twice or not at all. A box with an unclaimed
            face is not a closed domain, and blockMesh's default patch would
            silently absorb it.
    """
    x_min, x_max, y_min, y_max, z_min, z_max = (float(v) for v in bounds)
    for axis, (lo, hi) in zip("xyz", ((x_min, x_max), (y_min, y_max), (z_min, z_max))):
        if not hi > lo:
            raise ValueError(f"{axis} bounds are inverted or empty: {lo} .. {hi}")

    nx, ny, nz = (int(v) for v in divisions)
    if min(nx, ny, nz) < 1:
        raise ValueError(f"cell divisions must be >= 1, got {(nx, ny, nz)}")

    claimed: dict[str, str] = {}
    for patch in patches:
        for key in patch.faces:
            if key not in BOX_FACES:
                raise ValueError(
                    f"patch {patch.name!r}: unknown box face {key!r}; "
                    f"valid: {sorted(BOX_FACES)}")
            if key in claimed:
                raise ValueError(
                    f"box face {key!r} is claimed by both {claimed[key]!r} and "
                    f"{patch.name!r}")
            claimed[key] = patch.name
    missing = sorted(set(BOX_FACES) - set(claimed))
    if missing:
        raise ValueError(
            f"box faces {missing} are not assigned to any patch; the domain would "
            f"not be closed")

    # Canonical OpenFOAM ordering: local x1 = +x, x2 = +y, x3 = +z, so the
    # (nx ny nz) triple is applied to the axes its name implies.
    verts = [
        (x_min, y_min, z_min), (x_max, y_min, z_min),
        (x_max, y_max, z_min), (x_min, y_max, z_min),
        (x_min, y_min, z_max), (x_max, y_min, z_max),
        (x_max, y_max, z_max), (x_min, y_max, z_max),
    ]

    lines = header("blockMeshDict", generator, note)
    lines += ["scale   1;", "", "vertices", "("]
    lines += [f"    {fmt_point(v)}" for v in verts]
    lines += [
        ");",
        "",
        "blocks",
        "(",
        f"    hex (0 1 2 3 4 5 6 7) ({nx} {ny} {nz}) simpleGrading (1 1 1)",
        ");",
        "",
        "// No curved edges: every curved surface is introduced by snappyHexMesh.",
        "edges",
        "(",
        ");",
        "",
        "boundary",
        "(",
    ]
    for patch in patches:
        lines += [f"    {patch.name}", "    {", f"        type {patch.type};"]
        if patch.comment:
            lines.append(f"        // {patch.comment}")
        lines += ["        faces", "        ("]
        for key in patch.faces:
            a, b, c, d = BOX_FACES[key]
            lines.append(f"            ({a} {b} {c} {d})   // {key}")
        lines += ["        );", "    }", ""]
    lines += [
        ");",
        "",
        "mergePatchPairs",
        "(",
        ");",
        "",
        "// ************************************************************************* //",
    ]
    return "\n".join(lines) + "\n"


def uniform_divisions(bounds, cell_size_m: float) -> tuple[int, int, int]:
    """Cell counts giving cells as close to cubic as rounding allows.

    Args:
        bounds: ``(x_min, x_max, y_min, y_max, z_min, z_max)`` [m].
        cell_size_m: target background cell size [m].

    Returns:
        ``(nx, ny, nz)``, each at least 1.

    snappyHexMesh's octree halves a cell in all three directions at once, so a
    background cell that is not roughly cubic stays not-roughly-cubic at every
    refinement level. Rounding to the nearest count per axis keeps the aspect
    ratio within one rounding step of 1.
    """
    if cell_size_m <= 0.0:
        raise ValueError(f"cell size must be positive, got {cell_size_m}")
    x_min, x_max, y_min, y_max, z_min, z_max = (float(v) for v in bounds)
    return (
        max(1, round((x_max - x_min) / cell_size_m)),
        max(1, round((y_max - y_min) / cell_size_m)),
        max(1, round((z_max - z_min) / cell_size_m)),
    )
