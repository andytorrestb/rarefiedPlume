r"""Per-Kn slice-imagery specs, written from the manifest rather than typed.

``cases/cai2012-health/viz.yaml`` pins ``sampling.time_min`` to that family's
averaging start, 5.658e-3 s, as a literal -- correct there because its startup
is fixed at two transits, and kept honest by a test. Here the startup is Cai's
10^4 reference collision times, 0.0501 s, and a literal copied from either file
would be wrong. So the family's ``viz.yaml`` carries what is common, and this
module writes one small spec per Kn that ``extends`` it and adds what depends on
the case:

* ``sampling.time_min`` = the group's ``average_start_s`` from the manifest --
  only frames that HAVE a ``*Mean`` field are drawn;
* a derived ``n_over_n0 = rhoN{mean} / n0`` with that Kn's ``n0``, on the same
  fixed logarithmic range for every Kn, so the four groups are drawn on one
  normalised scale. Raw ``rhoN`` spans five decades of ``n0`` across this study
  and could not share a range.

``derived`` and ``fields`` are LISTS, and a spec that extends another replaces
its lists wholesale (``plumetools.viz.spec._merge``), so the generated spec
carries the base file's entries followed by its own.
"""

from __future__ import annotations

import os
from pathlib import Path

import yaml

#: The normalised density range, the same as :data:`plumetools.cai2012ext.figures.PLANE_FIELDS`.
N_OVER_N0_RANGE = (1.0e-4, 1.0)


def group_specs(manifest: dict, base_spec: Path) -> dict:
    """``{cai_case: (spec_dict, [case paths])}``, one per Kn group."""
    base = yaml.safe_load(Path(base_spec).read_text(encoding="utf-8")) or {}
    groups = {}
    for entry in manifest.get("cases") or []:
        groups.setdefault(entry["cai_case"], []).append(entry)

    specs = {}
    for name, members in groups.items():
        starts = sorted({float(m["average_start_s"]) for m in members})
        densities = sorted({float(m["n0_per_m3"]) for m in members})
        if len(starts) != 1 or len(densities) != 1:
            raise ValueError(
                f"{name}: the four levels disagree on the averaging start "
                f"{starts} or n0 {densities}; regenerate before rendering")
        derived = list(base.get("derived") or []) + [{
            "name": "n_over_n0",
            "expression": f"rhoN{{mean}}/{densities[0]:.9e}",
            "units": "-",
            "log": True,
        }]
        fields = [{"name": "n_over_n0", "log": True,
                   "range": list(N_OVER_N0_RANGE)}] + list(base.get("fields") or [])
        specs[name] = ({
            "version": base.get("version", 1),
            "sampling": {"time": "all", "time_min": starts[0]},
            "derived": derived,
            "fields": fields,
        }, [m["path"] for m in members])
    return specs


def write_group_specs(manifest: dict, base_spec: Path, out_dir: Path) -> dict:
    """Write each group's spec into ``out_dir``; return ``{name: (path, cases)}``."""
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    written = {}
    for name, (spec, cases) in group_specs(manifest, base_spec).items():
        path = out_dir / f"viz-{name}.yaml"
        relative = os.path.relpath(Path(base_spec).resolve(), out_dir.resolve())
        document = {"version": spec["version"],
                    "extends": relative.replace("\\", "/"),
                    **{k: v for k, v in spec.items() if k != "version"}}
        path.write_text(
            f"# GENERATED by AllpostCases from manifest.yaml for {name} -- "
            f"do not edit.\n"
            f"# time_min is this group's averaging start; n_over_n0 divides by "
            f"its n0.\n\n"
            + yaml.safe_dump(document, sort_keys=False, default_flow_style=False),
            encoding="utf-8", newline="\n")
        written[name] = (path, cases)
    return written
