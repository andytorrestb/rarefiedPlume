"""Generate the plate family's cases from ``study.yaml`` (spec §1, §3, §5).

Each case is the template ``baseCase/case.yaml`` with the exit Knudsen number,
the plate stand-off, the domain length and the mean-free-path refinement cones
written in, plus ``unigas.yaml`` and the case scripts copied beside it.
Idempotent: a case is rewritten unless it holds solver output, which is refused.
"""
from __future__ import annotations

import math
import shutil
import tempfile
from concurrent.futures import ProcessPoolExecutor
from dataclasses import asdict, dataclass
from pathlib import Path

import yaml

from plumetools.plateugf import sizing

SCRIPTS = ("Allmesh", "Allrun", "Allclean", "runCase.sh", "runMesh.sh")
HEADER = (
    "# GENERATED by cases/plate-unigas/generate_cases.py from baseCase/case.yaml\n"
    "# and study.yaml. Do not edit: change those and regenerate.\n"
    "# Design: docs/superpowers/specs/2026-11-24-plate-impingement-kn-sweep-unigasfoam-design.md\n\n"
)


class GenerationError(RuntimeError):
    """A case cannot be (re)generated as asked."""


@dataclass(frozen=True)
class PlannedCase:
    name: str
    kn_name: str
    knudsen: float
    standoff_over_D: int
    standoff_m: float
    x_max_m: float


@dataclass
class CaseEntry:
    name: str
    knudsen: float
    standoff_over_D: int
    cells_estimate: float | None = None
    particles_estimate: float | None = None
    memory_gb: float | None = None
    steps: int | None = None


def load_study(family_root: Path) -> dict:
    return yaml.safe_load((Path(family_root) / "study.yaml").read_text(encoding="utf-8"))


def _template(family_root: Path, study: dict) -> dict:
    path = Path(family_root) / study.get("base_case", "baseCase") / "case.yaml"
    return yaml.safe_load(path.read_text(encoding="utf-8"))


def plan_cases(study: dict, template: dict | None = None) -> list[PlannedCase]:
    """The 7 x 3 matrix, Kn as listed, then stand-off."""
    diameter = float((template or {}).get("nozzle", {}).get("exit_diameter_m", 0.2))
    thickness = float((template or {}).get("plate", {}).get("thickness_m", 0.25))
    behind = float(study.get("margin_behind_plate_m", 1.75))
    out = []
    for kn in study["kn_cases"]:
        for zd in study["standoffs_over_D"]:
            standoff = float(zd) * diameter
            out.append(PlannedCase(
                name=f"{kn['name']}_zD{int(zd)}", kn_name=str(kn["name"]),
                knudsen=float(kn["Kn"]), standoff_over_D=int(zd), standoff_m=standoff,
                x_max_m=standoff + thickness + behind))
    return out


def has_solver_output(case_dir: Path) -> bool:
    """A time directory after 0, in the case or in any processor directory."""
    case_dir = Path(case_dir)
    bases = [case_dir, *sorted(case_dir.glob("processor*"))]
    for base in bases:
        if not base.is_dir():
            continue
        for entry in base.iterdir():
            try:
                if entry.is_dir() and float(entry.name) > 0.0:
                    return True
            except ValueError:
                continue
    return False


def _limits(cfg: dict) -> tuple[float, float]:
    """The domain extents nozzleplume will build: rounded up to background cells."""
    bg = float(cfg["mesh"]["background_cell_size_m"])
    up = lambda v: math.ceil(round(float(v) / bg, 9)) * bg  # noqa: E731
    dom = cfg["domain"]
    return up(dom["x_max_m"]), math.hypot(up(dom["y_half_m"]), up(dom["z_half_m"]))


_TABLES: dict = {}


def _table(x_limit: float, rho_limit: float, radius: float, speed_ratio: float):
    key = (round(x_limit, 6), round(rho_limit, 6), radius, speed_ratio)
    if key not in _TABLES:
        _TABLES[key] = sizing.density_table(x_limit, rho_limit, radius, speed_ratio)
    return _TABLES[key]


def case_config(template: dict, planned: PlannedCase, sizing_cfg: dict,
                study_meta: dict | None = None) -> dict:
    """The template with this case's parameters and refinement cones written in."""
    cfg = yaml.safe_load(yaml.safe_dump(template))
    cfg["exit"]["knudsen"] = planned.knudsen
    cfg["plate"]["standoff_m"] = planned.standoff_m
    cfg["domain"]["x_max_m"] = planned.x_max_m
    cfg.setdefault("meta", {}).update({
        "case_name": planned.name, "kn_case": planned.kn_name,
        "knudsen": planned.knudsen, "standoff_over_D": planned.standoff_over_D,
        **(study_meta or {})})
    x_limit, rho_limit = _limits(cfg)
    diameter = float(cfg["nozzle"]["exit_diameter_m"])
    table = _table(x_limit, rho_limit, 0.5 * diameter, float(cfg["exit"]["speed_ratio"]))
    cfg["mesh"]["refinement_regions"] = sizing.refinement_regions(
        table, knudsen=planned.knudsen, diameter_m=diameter,
        x_limit_m=x_limit, rho_limit_m=rho_limit,
        background_m=float(cfg["mesh"]["background_cell_size_m"]),
        max_level=int(sizing_cfg.get("max_level", 6)),
        floor_m=float(sizing_cfg.get("floor_m", 0.01)),
        geo_fraction=float(sizing_cfg.get("geo_fraction", 0.05)))
    return cfg


def write_case(family_root: Path, case_dir: Path, cfg: dict, study: dict) -> Path:
    if has_solver_output(case_dir):
        raise GenerationError(
            f"{case_dir} holds solver output: it is never regenerated. Move it "
            f"aside (or ./Allclean it) first.")
    base = Path(family_root) / study.get("base_case", "baseCase")
    case_dir.mkdir(parents=True, exist_ok=True)
    (case_dir / "case.yaml").write_text(HEADER + yaml.safe_dump(cfg, sort_keys=False),
                                        encoding="utf-8", newline="\n")
    shutil.copy2(base / "unigas.yaml", case_dir / "unigas.yaml")
    for name in SCRIPTS:
        shutil.copy2(base / name, case_dir / name)
    return case_dir


def _estimate(case_dir: str) -> dict:
    from plumetools.nozzleplume import workflow as npw
    from plumetools.plateugf.workflow import BYTES_PER_CELL, BYTES_PER_PARTICLE
    case = npw.load(Path(case_dir))
    cells = float(sum(case.plan.cells_by_level.values()))
    parcels = float(case.run.estimated_parcels)
    return {"cells_estimate": cells, "particles_estimate": parcels,
            "memory_gb": (cells * BYTES_PER_CELL + parcels * BYTES_PER_PARTICLE) / 1e9,
            "steps": int(case.run.n_steps)}


def generate(family_root: Path, *, dry_run: bool = False, only: list[str] | None = None,
             estimate: bool = True, workers: int | None = None) -> list[CaseEntry]:
    """Write (or, dry, only plan) the cases; return one entry per case."""
    family_root = Path(family_root)
    study = load_study(family_root)
    template = _template(family_root, study)
    planned = [p for p in plan_cases(study, template) if not only or p.name in only]
    if only and len(planned) != len(set(only)):
        unknown = sorted(set(only) - {p.name for p in planned})
        raise GenerationError(f"unknown case(s) {unknown}")
    cases_dir = family_root / study.get("cases_dir", "Cases")
    scratch = Path(tempfile.mkdtemp(prefix="plate-unigas-")) if dry_run else None
    entries, dirs = [], []
    for p in planned:
        cfg = case_config(template, p, study.get("sizing") or {})
        case_dir = (scratch if dry_run else cases_dir) / p.name
        if dry_run:
            case_dir.mkdir(parents=True)
            (case_dir / "case.yaml").write_text(yaml.safe_dump(cfg, sort_keys=False), encoding="utf-8")
        else:
            write_case(family_root, case_dir, cfg, study)
        entries.append(CaseEntry(name=p.name, knudsen=p.knudsen, standoff_over_D=p.standoff_over_D))
        dirs.append(str(case_dir))
    if estimate and dirs:
        with ProcessPoolExecutor(max_workers=workers) as pool:
            for entry, numbers in zip(entries, pool.map(_estimate, dirs)):
                for key, value in numbers.items():
                    setattr(entry, key, value)
    if scratch is not None:
        shutil.rmtree(scratch, ignore_errors=True)
    if not dry_run and not only:
        manifest = family_root / study.get("manifest_name", "manifest-plate.yaml")
        manifest.write_text(
            "# GENERATED by generate_cases.py: the cases and their pre-run estimates.\n"
            + yaml.safe_dump({"cases": [asdict(e) for e in entries]}, sort_keys=False),
            encoding="utf-8", newline="\n")
    return entries


def stage_smoke(family_root: Path) -> Path:
    """Write ``Smoke/<case>``: the coarse, short laptop smoke case (spec §8)."""
    family_root = Path(family_root)
    study = load_study(family_root)
    smoke = study["smoke"]
    template = yaml.safe_load(yaml.safe_dump(_template(family_root, study)))
    template["mesh"]["background_cell_size_m"] = float(smoke["background_cell_size_m"])
    template["mesh"]["plate_refinement_level"] = int(smoke["plate_refinement_level"])
    for key in ("transient_domain_transits", "sampling_domain_transits", "n_subdomains"):
        template["dsmc"][key] = smoke[key]
    template["execution_profile"] = "smoke"
    planned = {p.name: p for p in plan_cases(study, template)}[smoke["case"]]
    cfg = case_config(template, planned, {
        "floor_m": smoke["floor_m"], "geo_fraction": smoke["geo_fraction"],
        "max_level": smoke["max_level"]})
    cfg["meta"]["note"] = "LAPTOP SMOKE RUN: coarse and short; proves the chain, not results."
    return write_case(family_root, family_root / "Smoke" / planned.name, cfg, study)


def table(entries: list[CaseEntry]) -> list[str]:
    lines = [f"{'case':<18}{'Kn':>9}{'z/D':>5}{'cells':>14}{'parcels':>11}{'memory GB':>11}{'steps':>10}"]
    for e in entries:
        cells = f"{e.cells_estimate:,.0f}" if e.cells_estimate is not None else "-"
        parcels = f"{e.particles_estimate:.3g}" if e.particles_estimate is not None else "-"
        memory = f"{e.memory_gb:.1f}" if e.memory_gb is not None else "-"
        steps = f"{e.steps:,}" if e.steps is not None else "-"
        lines.append(f"{e.name:<18}{e.knudsen:>9g}{e.standoff_over_D:>5}{cells:>14}"
                     f"{parcels:>11}{memory:>11}{steps:>10}")
    return lines
