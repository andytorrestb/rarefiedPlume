"""Batch scripts for one hybrid case: resource-aware, resumable, nothing invented.

What is reused, and from where
------------------------------
* the cluster environment: ``cases/cai2012-kn-extension/hpc_env.sh`` (Spack,
  Lmod, OpenMPI, OpenFOAM v2512, the repository's ``.venv``), sourced as that
  family's job scripts source it. ``HYBRID_HPC_ENV`` overrides the path;
* the PBS queue ``longq``, ``nodes=1:ppn=192`` and the 120 h ceiling: copied
  from ``cases/cai2012-kn-extension/baseCase/runCase.sh`` and marked as such.

SLURM has no existing settings in this repository, so its partition and
account are ``__SET_ME__`` placeholders that make ``sbatch`` fail until set.

The rank count is the profile's ``resources.max_ranks`` (never "all cores");
the walltime is three times the estimate, at least one hour, at most the
ceiling. A job that runs out of walltime is resubmitted BY HAND with the same
command: every stage resumes from the newest checkpoint complete on every rank.

Libraries must be compiled on the cluster, separately from WSL::

    source <hpc_env.sh>
    applications/dsmcBoundaryModels/Allwmake
    applications/thermophysicalModels/Allwmake
"""

from __future__ import annotations

import math
from pathlib import Path

KN_EXT_RUNCASE = "cases/cai2012-kn-extension/baseCase/runCase.sh"
DEFAULT_ENV = "cases/cai2012-kn-extension/hpc_env.sh"
PBS_DEFAULTS = {"queue": "longq", "ppn": 192, "max_walltime_h": 120}


def walltime_hours(estimate_s: float | None, ceiling_h: float) -> int:
    if not estimate_s or not math.isfinite(estimate_s):
        return int(ceiling_h)
    return int(min(ceiling_h, max(1.0, math.ceil(3.0 * estimate_s / 3600.0))))


def render(scheduler: str, *, case_dir: Path, repo: Path, stage: str, ranks: int,
           hours: int, name: str) -> str:
    env = f'${{HYBRID_HPC_ENV:-{repo / DEFAULT_ENV}}}'
    body = [
        "set -eo pipefail",
        "trap 'status=$?; printf \"FAILED: exit=%d line=%d command=%s\\n\" \"$status\" "
        "\"$LINENO\" \"$BASH_COMMAND\" >&2; exit \"$status\"' ERR",
        f'CASE="{case_dir}"',
        f'REPO="{repo}"',
        f'HPC_ENV={env}',
        '[ -f "$HPC_ENV" ] || { echo "FAILED: no $HPC_ENV (set HYBRID_HPC_ENV)" >&2; exit 1; }',
        "# hpc_env.sh refuses set -u (Lmod and OpenFOAM read unset variables)",
        'source "$HPC_ENV"',
        'export PATH="$FOAM_APPBIN:$PATH"',
        f'echo ">>> {stage} for $CASE on {ranks} ranks"',
        f'bash "$REPO/cases/cai2012-hybrid/Allrun" "$CASE" {stage} -np {ranks}',
        f'echo "<<< {stage} done"',
    ]
    if scheduler == "pbs":
        head = ["#PBS -S /bin/bash",
                f"#PBS -q {PBS_DEFAULTS['queue']}      # copied from {KN_EXT_RUNCASE}; verify",
                f"#PBS -l walltime={hours}:00:00",
                f"#PBS -l nodes=1:ppn={min(ranks, PBS_DEFAULTS['ppn'])}   # node layout from {KN_EXT_RUNCASE}",
                f"#PBS -N {name}", "#PBS -m abe   # add '#PBS -M <you>' to be mailed"]
    elif scheduler == "slurm":
        head = ["#!/bin/bash",
                "#SBATCH --partition=__SET_ME__   # no SLURM settings exist in this repository",
                "#SBATCH --account=__SET_ME__",
                "#SBATCH --nodes=1", f"#SBATCH --ntasks={ranks}",
                f"#SBATCH --time={hours}:00:00", f"#SBATCH --job-name={name}"]
    else:
        head = ["#!/bin/bash", "# no scheduler: run directly"]
    note = ["#", f"# Generated by plumetools.hybridplume.hpc for stage '{stage}'.",
            "# Resubmit the same script after a walltime kill: the stage resumes from",
            "# the newest checkpoint every rank wrote completely.", ""]
    return "\n".join(head + note + body) + "\n"


def write_scripts(case_dir: Path, repo: Path, cfg, scheduler: str, ranks: int | None,
                  estimates: dict) -> dict:
    case_dir = Path(case_dir).resolve()
    out_dir = case_dir / "hpc"
    out_dir.mkdir(parents=True, exist_ok=True)
    n = int(ranks or cfg.get("resources.max_ranks", 1))
    ceiling = PBS_DEFAULTS["max_walltime_h"]
    written = {}
    ext = {"pbs": "pbs", "slurm": "slurm", "none": "sh"}[scheduler]
    for stage, est in (("cfd", estimates.get("cfd")), ("dsmc", estimates.get("dsmc")),
                       ("crossings", 600.0), ("post-cfd", 3600.0), ("post-dsmc", 3600.0)):
        hours = walltime_hours(est, ceiling)
        text = render(scheduler, case_dir=case_dir, repo=Path(repo).resolve(), stage=stage,
                      ranks=n if stage in ("cfd", "dsmc", "crossings") else 1, hours=hours,
                      name=f"hyb-{stage}")
        path = out_dir / f"run_{stage}.{ext}"
        path.write_text(text)
        written[stage] = {"path": str(path), "walltime_h": hours,
                          "ranks": n if stage in ("cfd", "dsmc", "crossings") else 1}
    return written
