r"""The full 3-D continuum precursor: an OpenCFD ``rhoCentralFoam`` case.

Laminar compressible Navier--Stokes--Fourier for the same argon the DSMC runs:
``hConst`` (calorically perfect, ``cp = 5R/2``), ``perfectGas``, and tabulated
transport sampled from :meth:`Gas.viscosity` and :meth:`Gas.conductivity` --
the VHS power law, not Sutherland. The table needs ``libhybridPlumeThermo.so``
(``applications/thermophysicalModels``); OpenFOAM v2512 does not compile
tabulated transport for ``psiThermo``.

Boundary conditions
-------------------
=============  ===========================  ==================================
patch          p / T / U                    meaning
=============  ===========================  ==================================
source         fixedValue pe / Te / (Ue,0,0) the uniform exit state. The exit
                                            Mach number is 2.19, so every
                                            characteristic enters and all three
                                            may be fixed
exitPlane      waveTransmissive / inletOutlet / inletOutlet
farField       (fieldInf = background)      open, non-reflecting outflow. Gas
                                            leaving through ``x = 0`` outside
                                            the disk leaves the problem, as in
                                            the DSMC (molecules deleted there)
=============  ===========================  ==================================

Vacuum and the background floor
-------------------------------
A central scheme cannot advance an exact vacuum: ``p = rho = 0`` has no sound
speed. The domain is therefore initialised, and the open boundaries relax
towards, a background state ``p_bg = r_bg pe`` at ``T_bg`` (both in the
configuration, ``cfd.background_pressure_ratio`` and
``cfd.background_temperature_K``). It is a numerical floor, not an ambient gas:
:mod:`plumetools.hybridplume.workflow` runs the precursor at more than one ratio
and reports how much the retained continuum core moves.

The floor has a temperature as well as a pressure. ``rhoCentralFoam`` advances
the viscous work ``div(tau.U)`` explicitly, so its step must respect
``dt < dx^2 rho / mu`` in the *least* dense gas. At 300 K and ``p_bg/pe =
1e-4`` that limit is ~1e-8 s against a convective step of ~1e-6 s, and the
first step drives the temperature negative (measured; Sutherland transport
fails identically, so it is not the tabulated library). A cold floor raises
``rho_bg`` at the same ``p_bg`` and lowers ``mu``, so ``nu_bg`` falls as
``T_bg^1.81``; ``maxDeltaT`` is additionally capped at
``cfd.viscous_dt_factor * dx^2 rho_bg / mu(T_bg)`` (reported in setup.json).

Nothing here clips, limits or rescales a state after the solve.
"""

from __future__ import annotations

import math
from pathlib import Path

import numpy as np

from .config import CaseConfig
from .mesh import PATCHES, MeshPlan
from .physics import SourceState

GENERATOR = "plumetools.hybridplume.cfd"
THERMO_LIB = "libhybridPlumeThermo.so"


def _header(cls: str, obj: str, note: str = "", location: str | None = None) -> list:
    lines = ["/*--------------------------------*- C++ -*----------------------------------*\\",
             f"  Generated by {GENERATOR}. Regenerate from hybrid.yaml; do not edit.",
             f"  {note}" if note else "  ",
             "\\*---------------------------------------------------------------------------*/",
             "FoamFile", "{", "    version     2.0;", "    format      ascii;",
             f"    class       {cls};"]
    if location:
        lines.append(f'    location    "{location}";')
    lines += [f"    object      {obj};", "}", ""]
    return lines


def _f(v) -> str:
    return f"{float(v):.10g}"


def transport_table(source: SourceState, t_lo: float = 0.5, t_hi: float = 5000.0,
                    n: int = 240) -> tuple:
    """``(T, mu, kappa)`` sampled log-uniformly, and the worst interpolation error.

    The error is measured, not assumed: linear interpolation between the
    tabulated points is compared with the exact power law at the midpoint of
    every interval in ``log T``.
    """
    gas = source.gas
    t = np.geomspace(t_lo, t_hi, n)
    mu = gas.viscosity(t)
    kappa = gas.conductivity(t)
    mid = np.sqrt(t[:-1] * t[1:])
    lam = (mid - t[:-1]) / (t[1:] - t[:-1])
    interp = mu[:-1] + lam * (mu[1:] - mu[:-1])
    err = float(np.max(np.abs(interp / gas.viscosity(mid) - 1.0)))
    return t, mu, kappa, err


def render_thermophysical_properties(source: SourceState, table=None) -> str:
    gas = source.gas
    t, mu, kappa, err = table or transport_table(source)
    lines = _header("dictionary", "thermophysicalProperties",
                    f"argon, VHS-consistent transport (omega {gas.omega}); "
                    f"table interpolation error <= {err:.1e}")
    lines += [
        "// Needs libhybridPlumeThermo.so (controlDict libs): OpenFOAM v2512 has no",
        "// psiThermo instantiation of tabulated transport.",
        "thermoType", "{", "    type            hePsiThermo;", "    mixture         pureMixture;",
        "    transport       tabulated;", "    thermo          hConst;",
        "    equationOfState perfectGas;", "    specie          specie;",
        "    energy          sensibleInternalEnergy;", "}", "",
        "mixture", "{", "    specie", "    {",
        f"        molWeight   {gas.molar_mass_g_per_mol:.10g};  // from m = {gas.mass_kg} kg",
        "    }", "    thermodynamics", "    {",
        f"        Cp          {gas.cp:.10g};   // 5R/2",
        "        Hf          0;", "    }", "    transport", "    {",
        f"        // mu = {gas.mu_ref:.6e} (T/{gas.t_ref_K})^{gas.omega}, Bird eq 4.62;"
        f" kappa = mu cp / Pr, Pr = {gas.prandtl:.6g}",
        "        mu", "        ("]
    lines += [f"            ({_f(ti)} {mi:.10e})" for ti, mi in zip(t, mu)]
    lines += ["        );", "        kappa", "        ("]
    lines += [f"            ({_f(ti)} {ki:.10e})" for ti, ki in zip(t, kappa)]
    lines += ["        );", "    }", "}", ""]
    return "\n".join(lines) + "\n"


def background_state(cfg: CaseConfig, source: SourceState) -> dict:
    ratio = float(cfg.get("cfd.background_pressure_ratio", 1e-4))
    t_bg = float(cfg.get("cfd.background_temperature_K", source.temperature_K))
    p_bg = ratio * source.pressure
    return {"pressure_Pa": p_bg, "temperature_K": t_bg, "ratio": ratio,
            "density_kg_m3": p_bg / (source.gas.gas_constant * t_bg)}


def render_fields(cfg: CaseConfig, source: SourceState) -> dict:
    bg = background_state(cfg, source)
    l_inf = float(cfg.get("cfd.l_inf_over_D", 1.0)) * source.diameter_m
    s, e, f = PATCHES["source"], PATCHES["exit_plane"], PATCHES["far_field"]
    gamma = source.gas.gamma

    def field(cls, name, dims, internal, source_entry, open_entry):
        lines = _header(cls, name, location="0")
        lines += [f"dimensions      {dims};", "", f"internalField   {internal};", "",
                  "boundaryField", "{", f"    {s}", "    {"]
        lines += [f"        {x}" for x in source_entry]
        lines += ["    }"]
        for patch in (e, f):
            lines += [f"    {patch}", "    {"] + [f"        {x}" for x in open_entry] + ["    }"]
        lines += ["}", ""]
        return "\n".join(lines) + "\n"

    p = field("volScalarField", "p", "[1 -1 -2 0 0 0 0]", f"uniform {_f(bg['pressure_Pa'])}",
              ["type fixedValue;", f"value uniform {_f(source.pressure)};"],
              ["type waveTransmissive;", "field p;", "psi thermo:psi;",
               f"gamma {_f(gamma)};", f"fieldInf {_f(bg['pressure_Pa'])};",
               f"lInf {_f(l_inf)};", f"value uniform {_f(bg['pressure_Pa'])};"])
    t = field("volScalarField", "T", "[0 0 0 1 0 0 0]", f"uniform {_f(bg['temperature_K'])}",
              ["type fixedValue;", f"value uniform {_f(source.temperature_K)};"],
              ["type inletOutlet;", f"inletValue uniform {_f(bg['temperature_K'])};",
               f"value uniform {_f(bg['temperature_K'])};"])
    u = field("volVectorField", "U", "[0 1 -1 0 0 0 0]", "uniform (0 0 0)",
              ["type fixedValue;", f"value uniform ({_f(source.velocity)} 0 0);"],
              ["type inletOutlet;", "inletValue uniform (0 0 0);", "value uniform (0 0 0);"])
    return {"p": p, "T": t, "U": u}


def timing(cfg: CaseConfig, source: SourceState, plan: MeshPlan) -> dict:
    x_max = plan.x_segments[-1].hi
    transit = x_max / source.velocity
    n_transits = float(cfg.get("cfd.end_time_transits", 4.0))
    writes_per_transit = int(cfg.get("cfd.writes_per_transit", 4))
    write_interval = transit / writes_per_transit
    n_writes = max(1, int(math.ceil(n_transits * writes_per_transit)))
    # Initial step: the explicit Courant limit on the smallest cell at the
    # fastest signal speed the expansion can reach, sqrt(U^2 + 5RT) + c.
    u_lim = math.sqrt(source.velocity ** 2 + 5.0 * source.gas.gas_constant
                      * source.temperature_K)
    signal = u_lim + source.sound_speed
    courant = float(cfg.get("cfd.max_courant", 0.2))
    dt0 = 0.1 * courant * plan.core_cell_m / signal
    # rhoCentralFoam advances the viscous work div(tau.U) explicitly. Its
    # stability limit, dt < dx^2 rho / mu, is set by the LEAST dense gas -- the
    # background floor -- and maxCo knows nothing about it. Measured: with
    # p_bg/pe = 1e-4 at 300 K the first step drives T negative.
    bg = background_state(cfg, source)
    mu_bg = float(source.gas.viscosity(bg["temperature_K"]))
    factor = float(cfg.get("cfd.viscous_dt_factor", 0.25))
    dt_visc = factor * plan.core_cell_m ** 2 * bg["density_kg_m3"] / mu_bg
    max_dt = min(write_interval / 10.0, dt_visc)
    return {"transit_s": transit, "write_interval_s": write_interval,
            "end_time_s": n_writes * write_interval, "n_writes": n_writes,
            "initial_dt_s": min(dt0, max_dt), "max_courant": courant,
            "viscous_dt_limit_s": dt_visc, "viscous_dt_factor": factor,
            "max_delta_t_s": max_dt,
            "convective_dt_estimate_s": courant * plan.core_cell_m / signal}


def render_control_dict(cfg: CaseConfig, source: SourceState, plan: MeshPlan) -> str:
    tm = timing(cfg, source, plan)
    lines = _header("dictionary", "controlDict",
                    f"{tm['n_writes']} writes of {tm['write_interval_s']:.6e} s; "
                    f"one domain transit = {tm['transit_s']:.6e} s")
    lines += [
        f'libs ("{THERMO_LIB}");', "",
        "application     rhoCentralFoam;", "startFrom       latestTime;", "startTime       0;",
        "stopAt          endTime;", f"endTime         {tm['end_time_s']:.10g};",
        f"deltaT          {tm['initial_dt_s']:.6e};",
        "// adjustableRunTime keeps every write on a multiple of writeInterval, so a",
        "// resume from any written time stays on the same schedule.",
        "writeControl    adjustableRunTime;",
        f"writeInterval   {tm['write_interval_s']:.10g};",
        f"purgeWrite      {int(cfg.get('cfd.purge_write', 0))};",
        "writeFormat     ascii;", "writePrecision  12;", "writeCompression off;",
        "timeFormat      general;", "timePrecision   10;", "runTimeModifiable false;",
        "adjustTimeStep  yes;", f"maxCo           {_f(tm['max_courant'])};",
        "// maxDeltaT is the SMALLER of a tenth of a write interval and the explicit",
        f"// viscous limit of the background state ({tm['viscous_dt_limit_s']:.3e} s;",
        f"// convective step ~ {tm['convective_dt_estimate_s']:.3e} s).",
        f"maxDeltaT       {_f(tm['max_delta_t_s'])};", "",
        "functions", "{",
        "    // Mass through every boundary, from the solver's own face flux phi:",
        "    // the numerical flux the continuity equation used, not a reconstruction.",
        "    boundaryMassFlux",
        "    {",
        "        type            surfaceFieldValue;",
        '        libs            ("fieldFunctionObjects");',
        "        writeControl    timeStep;", "        writeInterval   1;",
        "        log             false;", "        writeFields     false;",
        "        regionType      patch;",
        f"        name            {PATCHES['source']};",
        "        operation       sum;", "        fields          (phi);", "    }",
    ]
    for key, patch in (("exitPlaneMassFlux", PATCHES["exit_plane"]),
                       ("farFieldMassFlux", PATCHES["far_field"])):
        lines += [f"    {key}", "    {", "        ${boundaryMassFlux}",
                  f"        name            {patch};", "    }"]
    lines += [
        "    domainMass", "    {", "        type            volFieldValue;",
        '        libs            ("fieldFunctionObjects");',
        "        writeControl    timeStep;", "        writeInterval   1;",
        "        log             false;", "        writeFields     false;",
        "        regionType      all;", "        operation       volIntegrate;",
        "        fields          (rho rhoU rhoE);", "    }",
        "}", ""]
    return "\n".join(lines) + "\n"


def render_fv_schemes(cfg: CaseConfig) -> str:
    limiter = str(cfg.get("cfd.reconstruction_limiter", "vanLeer"))
    # TVD limiters have a vector ("V") form; first-order upwind does not.
    vector = limiter if limiter in ("upwind", "linearUpwind") else f"{limiter}V"
    lines = _header("dictionary", "fvSchemes",
                    "Kurganov-Tadmor central-upwind, limited reconstruction")
    lines += [
        "fluxScheme      Kurganov;", "",
        "ddtSchemes { default Euler; }", "",
        "// The diagnostic gradients for breakdown are recomputed in plumetools",
        "// (weighted least squares on the written cell values); these are the",
        "// solver's own, used for the viscous terms.",
        "gradSchemes { default Gauss linear; }", "",
        "divSchemes", "{", "    default         none;",
        "    div(tauMC)      Gauss linear;", "}", "",
        "laplacianSchemes { default Gauss linear corrected; }", "",
        "interpolationSchemes", "{", "    default         linear;",
        f"    reconstruct(rho) {limiter};", f"    reconstruct(U)  {vector};",
        f"    reconstruct(T)  {limiter};", "}", "",
        "snGradSchemes { default corrected; }", ""]
    return "\n".join(lines) + "\n"


def render_fv_solution() -> str:
    lines = _header("dictionary", "fvSolution")
    lines += [
        "solvers", "{",
        '    "(rho|rhoU|rhoE)" { solver diagonal; }',
        '    U { solver smoothSolver; smoother GaussSeidel; nSweeps 2; tolerance 1e-10; relTol 0; }',
        '    e { $U; tolerance 1e-10; relTol 0; }',
        "}", ""]
    return "\n".join(lines) + "\n"


def render_turbulence_properties() -> str:
    lines = _header("dictionary", "turbulenceProperties",
                    "laminar: no turbulence model in this increment")
    lines += ["simulationType laminar;", ""]
    return "\n".join(lines) + "\n"


def render_decompose_par_dict(n: int) -> str:
    lines = _header("dictionary", "decomposeParDict")
    lines += [f"numberOfSubdomains {int(n)};", "method scotch;", ""]
    return "\n".join(lines) + "\n"


def write_case(case_dir: Path, cfg: CaseConfig, source: SourceState, plan: MeshPlan,
               n_ranks: int = 1) -> dict:
    """Write every CFD dictionary and initial field. Returns paths and timing."""
    case_dir = Path(case_dir)
    for sub in ("0", "constant", "system"):
        (case_dir / sub).mkdir(parents=True, exist_ok=True)
    table = transport_table(source)
    written = []

    def put(rel, text):
        path = case_dir / rel
        path.write_text(text)
        written.append(path)

    put("constant/thermophysicalProperties", render_thermophysical_properties(source, table))
    put("constant/turbulenceProperties", render_turbulence_properties())
    for name, text in render_fields(cfg, source).items():
        put(f"0/{name}", text)
    put("system/controlDict", render_control_dict(cfg, source, plan))
    put("system/fvSchemes", render_fv_schemes(cfg))
    put("system/fvSolution", render_fv_solution())
    put("system/decomposeParDict", render_decompose_par_dict(n_ranks))
    return {"written": [str(p) for p in written], "timing": timing(cfg, source, plan),
            "background": background_state(cfg, source),
            "transport_table_max_rel_error": table[3]}
