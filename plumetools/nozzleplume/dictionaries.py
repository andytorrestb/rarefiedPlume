r"""Generate ``constant/dsmcProperties``, ``system/controlDict`` and friends.

``case.yaml`` is the one authoritative source of physical inputs, so these are
**generated** from it rather than shipped and patched. String substitution into
a checked-in dictionary silently does nothing if the file is reformatted, if the
value is already different, or if the case came from an older template, and none
of those is visible in the output.

What is generated
-----------------

========================================  =====================================
``constant/dsmcProperties``               species, collision and wall models,
                                          particle weight, the inflow model and
                                          its patch list
``system/controlDict``                    times, writing, ``libs``,
                                          ``fieldAverage``
``system/dsmcInitialiseDict``             the near-vacuum initial fill
``system/decomposeParDict``               subdomain count and method
``system/fvSchemes`` / ``fvSolution``     required by ``fvMesh``, unused by DSMC
========================================  =====================================

Generalised from :mod:`plumetools.cai2012.dictionaries`. Three things that
package fixes are configuration here: the species (not argon), the collision
model (elastic VHS, Larsen-Borgnakke, or none), and -- new, because there is a
wall to interact with -- the gas-surface model.
"""

from __future__ import annotations

from pathlib import Path

from plumetools.foamio.primitives import BANNER, SEPARATOR, write_lines

GENERATOR = "plumetools.nozzleplume.dictionaries"

#: The shared library that provides ``plumeFieldInflow``.
PLUME_LIB = "libplumeDsmcBoundaryModels.so"

#: The inflow boundary model. ``applications/dsmcBoundaryModels``.
INFLOW_MODEL = "plumeFieldInflow"

#: ``dsmc.collision_model`` to the type name ``dsmcFoam`` selects it by, where
#: the two differ.
#:
#: The collisionless model is the class ``NoBinaryCollision`` but registers
#: itself as ``none``: v2512 answers ``BinaryCollisionModel NoBinaryCollision;``
#: with "Unknown BinaryCollisionModel type", listing ``none`` among the valid
#: ones. ``case.yaml`` keeps the class name, because ``collision_model: none``
#: reads as "no model was chosen" rather than as a choice.
FOAM_COLLISION_MODEL = {"NoBinaryCollision": "none"}

#: Fields ``fieldAverage`` accumulates, and whether it also keeps the variance.
#:
#: ``fD`` and ``q`` first: on the plate patch they are the momentum and energy
#: the gas delivers, which is the result of an impingement case. Both are reset
#: every step and re-accumulated by ``DSMCParcel::hitWallPatch``, so a written
#: snapshot is one step's tally and only the mean can be read as a load.
#:
#: ``prime2Mean`` is ON for the two number densities and off for everything
#: else. It turns a sampled mean into a *measured* statistical error,
#: ``sqrt(dsmcRhoNPrime2Mean) / dsmcRhoNMean``, which is the only honest way to
#: judge a run whose particle weight was chosen by what the machine could hold.
#: OFF for the rest: ``prime2Mean`` of a vector is a symmTensor -- six extra
#: components per cell -- and nothing reads them.
AVERAGED_FIELDS = {
    "fD": False,
    "q": False,
    "rhoN": True,
    "rhoM": False,
    "dsmcRhoN": True,
    "momentum": False,
    "linearKE": False,
    "internalE": False,
    "iDof": False,
}


def _header(object_name: str, note: str, location: str | None = None) -> list[str]:
    lines = [
        BANNER,
        f"// GENERATED by {GENERATOR} from case.yaml -- do not edit.",
        "// Regenerate with ./Allmesh. case.yaml is the authoritative source.",
        f"// {note}",
        "FoamFile",
        "{",
        "    version     2.0;",
        "    format      ascii;",
        "    class       dictionary;",
    ]
    if location:
        lines.append(f'    location    "{location}";')
    lines += [f"    object      {object_name};", "}", SEPARATOR, ""]
    return lines


def _footer() -> list[str]:
    return ["",
            "// ************************************************************************* //"]


def _collision_coeffs(cfg) -> list[str]:
    """``BinaryCollisionModel`` and its coefficient dictionary."""
    model = cfg.dsmc.collision_model
    g = cfg.gas
    lines = ["// Binary Collision Model", "// ~~~~~~~~~~~~~~~~~~~~~~", ""]

    if model == "NoBinaryCollision":
        return lines + [
            "// COLLISIONLESS (dsmc.collision_model: NoBinaryCollision, which",
            "// dsmcFoam knows as 'none'). Molecules interact with the plate and",
            "// with nothing else. A diagnostic for the wall and inflow models --",
            "// at a dense exit it is not a model of the plume.",
            f"BinaryCollisionModel            {FOAM_COLLISION_MODEL[model]};",
        ]

    lines += [
        "// NTC is not a setting: it is the only collision-selection algorithm",
        "// DSMCCloud::collisions() implements.",
        "//",
        f"// VHS with omega = {float(g.omega):g}: the total cross-section is",
        "//     pi d^2 (2 k Tref / (m_r c_r^2))^(omega - 1/2) / Gamma(5/2 - omega)",
    ]
    if float(g.omega) == 0.5:
        lines += [
            "// which at omega = 0.5 is exactly pi d^2 -- a hard sphere -- and Tref",
            "// drops out. It is still a required entry.",
        ]
    else:
        lines += [
            f"// so the diameter {float(g.molecular_diameter_m):g} m and Tref are a"
            " pair: changing one",
            "// without the other changes the gas.",
        ]
    if model == "LarsenBorgnakkeVariableHardSphere":
        lines += [
            "//",
            "// Larsen-Borgnakke redistributes energy between translation and the",
            "// internal modes in 1 collision in relaxationCollisionNumber.",
        ]
    lines += [
        f"BinaryCollisionModel            {model};",
        "",
        f"{model}Coeffs",
        "{",
        f"    Tref                        {float(g.t_ref_K):g};",
    ]
    if model == "LarsenBorgnakkeVariableHardSphere":
        lines.append(f"    relaxationCollisionNumber   "
                     f"{float(cfg.dsmc.relaxation_collision_number):g};")
    lines.append("}")
    return lines


def _wall_coeffs(cfg, geom) -> list[str]:
    """``WallInteractionModel`` and, where it has one, its coefficients."""
    model = cfg.dsmc.wall_interaction_model
    lines = ["// Wall Interaction Model", "// ~~~~~~~~~~~~~~~~~~~~~~", ""]

    if geom.plate is None:
        lines += [
            "// This case has NO wall patches -- the nozzle injects and every",
            "// other boundary is open vacuum -- but DSMCCloud constructs the",
            "// model unconditionally, so one has to be named.",
        ]
    elif model == "MaxwellianThermal":
        lines += [
            "// Fully diffuse, fully accommodated: a molecule leaves the plate",
            "// with a Maxwellian at the WALL temperature. That temperature is not",
            "// a coefficient here -- the model reads it from cloud.boundaryT() on",
            f"// the wall face, where 0/boundaryT carries "
            f"{geom.plate.temperature_K:g} K.",
        ]
    elif model == "SpecularReflection":
        lines += [
            "// Mirror reflection. No energy exchange, so q is zero on the plate",
            "// and its temperature is never read.",
        ]
    else:
        lines += [
            "// diffuseFraction of the molecules leave thermalised to the wall",
            f"// temperature ({geom.plate.temperature_K:g} K, from 0/boundaryT);"
            " the rest reflect",
            "// specularly.",
        ]
    lines.append(f"WallInteractionModel            {model};")
    if model == "MixedDiffuseSpecular":
        lines += [
            "",
            f"{model}Coeffs",
            "{",
            f"    diffuseFraction             {float(cfg.dsmc.diffuse_fraction):g};",
            "}",
        ]
    return lines


def render_dsmc_properties(cfg, geom, exit_state, run) -> str:
    """``constant/dsmcProperties``.

    Args:
        cfg: the case config.
        geom: the geometry, for whether there is a wall.
        exit_state: the :class:`~plumetools.nozzleplume.exitstate.ExitState`.
        run: the :class:`~plumetools.nozzleplume.run.RunSettings`, for the weight.

    Raises:
        ValueError: for a non-positive particle weight.
    """
    weight = float(run.n_equivalent_particles)
    if not weight > 0.0:
        raise ValueError(f"nEquivalentParticles must be positive, got {weight}")

    g = cfg.gas
    species = g.species_name
    field = f"boundaryNumberDensity_{species}"

    lines = _header(
        "dsmcProperties",
        f"{species}: n = {exit_state.number_density_per_m3:.6e} 1/m^3 at the exit,"
        f" Kn = {exit_state.knudsen:.3e}.",
        location="constant")

    lines += [
        "// General Properties",
        "// ~~~~~~~~~~~~~~~~~~",
        "",
        "// Standard dsmcFoam has ONE particle weight for the whole domain --",
        "// DSMCCloud::nParticle_ is a single scalar. At this value an exit cell,",
        f"// the densest in the domain, holds {run.exit_particles_per_cell:.3g}"
        " parcels.",
    ]
    if run.weight_source == "case.yaml":
        lines.append("// Set directly: dsmc.n_equivalent_particles in case.yaml.")
    else:
        lines.append(
            f"// Derived from dsmc.target_particles_per_exit_cell = "
            f"{float(cfg.dsmc.target_particles_per_exit_cell):g}.")
    lines += [
        f"nEquivalentParticles            {weight:.6e};",
        "",
        "",
    ]
    lines += _wall_coeffs(cfg, geom)
    lines += ["", ""]
    lines += _collision_coeffs(cfg)
    lines += [
        "",
        "",
        "// Inflow Boundary Model",
        "// ~~~~~~~~~~~~~~~~~~~~~",
        "",
        "// applications/dsmcBoundaryModels/plumeFieldInflow. Two things stock",
        "// FreeStream cannot do: inject across a NAMED patch list, and read the",
        "// number density PER FACE.",
        "//",
        "// The first is what makes this case possible at all. FreeStream injects",
        "// on every patch-type boundary, so the vacuum boundaries would become",
        "// inlets; the only way to stop that is to declare them walls, which",
        "// replaces the vacuum with a reflecting box.",
        "//",
        "// The library is loaded by system/controlDict's libs() entry. Without",
        "// it the run stops with an unknown-model error -- there is no fallback.",
        f"InflowBoundaryModel             {INFLOW_MODEL};",
        "",
        f"{INFLOW_MODEL}Coeffs",
        "{",
        f"    patches ( {cfg.mesh.patch_names['nozzle']} );",
        "",
        "    numberDensityFields",
        "    {",
        f"        {species}    {field};",
        "    }",
        "}",
        "",
        "",
        "// Molecular species",
        "// ~~~~~~~~~~~~~~~~~",
        "",
        f"typeIdList                      ({species});",
        "",
        "moleculeProperties",
        "{",
        f"    {species}",
        "    {",
        f"        mass                            {float(g.molecular_mass_kg):.9g};",
        f"        diameter                        {float(g.molecular_diameter_m):.9g};",
        f"        internalDegreesOfFreedom        "
        f"{int(g.internal_degrees_of_freedom)};",
        f"        omega                           {float(g.omega):g};",
        "    }",
        "}",
    ]
    lines += _footer()
    return "\n".join(lines) + "\n"


def render_control_dict(cfg, run) -> str:
    """``system/controlDict``, including ``libs`` and ``fieldAverage``.

    ``fieldAverage`` is not decoration. ``DSMCCloud::resetFields`` zeroes the
    measurement fields every timestep, so a written ``rhoN`` or ``fD`` is one
    step's worth of parcels -- shot noise. The ``*Mean`` fields are what the
    post-processing reads.
    """
    lines = _header(
        "controlDict",
        f"dsmcFoam, deltaT {run.delta_t_s:g} s to {run.end_time_s:g} s "
        f"({run.n_steps} steps), averaging from {run.average_start_s:g} s.",
        location="system")

    lines += [
        "application     dsmcFoam;",
        "",
        "// The custom inflow boundary model. Build it with",
        "//     applications/dsmcBoundaryModels/Allwmake",
        "// Without this line dsmcFoam reports plumeFieldInflow as an unknown",
        "// InflowBoundaryModel and stops, which is the intended failure.",
        f'libs            ( "{PLUME_LIB}" );',
        "",
        "// 'latestTime', not 'startTime': re-running ./Allrun CONTINUES the case",
        "// from its newest time directory instead of restarting it. On a case",
        "// with no results this resolves to 0, so a fresh run is unaffected.",
        "//",
        "// The whole DSMC state is in each time directory -- lagrangian/dsmc/",
        "// holds the parcels, and fieldAverage's accumulators are in uniform/ --",
        "// so a resumed run continues both the flow and the averaging.",
        "//",
        "// purgeWrite 0 below is what makes this safe: no time directory is ever",
        "// deleted, so there is always something to resume from.",
        "startFrom       latestTime;",
        "startTime       0;",
        "stopAt          endTime;",
        f"endTime         {run.end_time_s:.10g};",
        "",
        f"// Courant {run.courant:.3f}: a molecule at U + 3 sigma crosses that",
        "// fraction of the smallest cell per step.",
        f"deltaT          {run.delta_t_s:.10g};",
        "",
        "// 'timeStep', not 'runTime'. Time::operator++ computes the runTime",
        "// write index as (value - startTime)/writeInterval, and on a RESUME",
        "// startTime is the resume point -- so the schedule starts again there",
        "// and a resumed leg shorter than one interval writes NOTHING. The step",
        "// index is global instead: each time directory stores it in uniform/time",
        "// and it continues across restarts.",
        "//",
        f"// {run.write_interval_steps} steps = {run.write_interval_s:g} s. The end",
        f"// time is a whole number of these ({run.n_writes} of them), so there is",
        "// a write exactly AT endTime wherever the run was resumed from.",
        "writeControl    timeStep;",
        f"writeInterval   {run.write_interval_steps};",
        "// Never purge: a deleted time directory is one fewer place to resume",
        "// from, and ./Allclean is the only thing here that removes one.",
        "purgeWrite      0;",
        "// ascii: the post-processing reads these files itself, and reads text.",
        "writeFormat     ascii;",
        "writePrecision  10;",
        "writeCompression off;",
        "timeFormat      general;",
        "timePrecision   6;",
        "runTimeModifiable true;",
        "adjustTimeStep  no;",
        "",
        "functions",
        "{",
        "    fieldAverage1",
        "    {",
        "        type            fieldAverage;",
        "        libs            (fieldFunctionObjects);",
        "        writeControl    writeTime;",
        "        // Everything before this is transient and is discarded.",
        f"        timeStart       {run.average_start_s:.10g};",
        f"        // {run.sampling_time_s:g} s of sampling,"
        f" {run.n_sampled_writes} of the {run.n_writes} writes.",
        "",
        "        fields",
        "        (",
    ]
    for name, prime2mean in AVERAGED_FIELDS.items():
        lines += [
            f"            {name}",
            "            {",
            "                mean        on;",
            f"                prime2Mean  {'on' if prime2mean else 'off'};",
            "                base        time;",
            "            }",
        ]
    lines += ["        );", "    }", "}"]
    lines += _footer()
    return "\n".join(lines) + "\n"


def render_dsmc_initialise_dict(cfg) -> str:
    """``system/dsmcInitialiseDict``: a near-vacuum fill, at rest.

    Not a physical initial state. The domain starts essentially empty and the
    plume fills it from the nozzle; the value only has to be small enough that
    the transient is short and non-zero so the cloud is not built from nothing.
    """
    d = cfg.dsmc
    lines = _header(
        "dsmcInitialiseDict",
        f"Near-vacuum seed: {d.initial_number_density_per_m3:g} 1/m^3 at rest.",
        location="system")
    lines += [
        "numberDensities",
        "{",
        f"    {cfg.gas.species_name}          {d.initial_number_density_per_m3:g};",
        "};",
        "",
        f"temperature     {d.initial_temperature_K:g};",
        "",
        "// At rest: the plume arrives through the nozzle, it is not already",
        "// streaming when the run starts.",
        "velocity        (0 0 0);",
    ]
    lines += _footer()
    return "\n".join(lines) + "\n"


def simple_split(n_subdomains: int) -> tuple:
    """Factor ``n`` into an ``(nx, ny, nz)`` split, preferring lateral cuts.

    Returns:
        ``(nx, ny, nz)`` whose product is exactly ``n_subdomains``.

    Factors go to the axis with the smallest count so far, taking ``y`` and
    ``z`` before ``x``, so a small rank count never cuts across the plume: the
    parcels are strung out along ``x``, and an ``(n 1 1)`` split would give the
    rank holding the nozzle most of them. The reasoning, with measurements, is
    in :func:`plumetools.cai2012.dictionaries.simple_split`.
    """
    n = int(n_subdomains)
    if n < 1:
        raise ValueError(f"n_subdomains must be >= 1, got {n_subdomains}")

    factors = []
    remainder = n
    divisor = 2
    while divisor * divisor <= remainder:
        while remainder % divisor == 0:
            factors.append(divisor)
            remainder //= divisor
        divisor += 1
    if remainder > 1:
        factors.append(remainder)
    factors.sort(reverse=True)

    counts = [1, 1, 1]
    for factor in factors:
        best = min((1, 2, 0), key=lambda axis: counts[axis])
        counts[best] *= factor
    return tuple(counts)


def render_decompose_par_dict(cfg) -> str:
    """``system/decomposeParDict``.

    ``scotch`` by default: the mesh is an octree, and a geometric split would
    cut straight through the refined volumes. Neither method is a *particle*
    decomposition -- DSMC cost follows parcels, and both balance cells -- so
    this is a throughput choice, not a correctness one. ``simple`` is there for
    when ``scotch`` hands one rank the whole exit region.
    """
    n = int(cfg.dsmc.n_subdomains)
    method = cfg.dsmc.decomposition_method
    lines = _header("decomposeParDict", f"{n} subdomains, {method}.",
                    location="system")
    lines += [
        "// DSMC cost follows PARCELS, not cells, and both methods here balance",
        "// cells. Which is faster is a property of the case; compare the per-rank",
        "// parcel counts in log.dsmcFoam before settling on one.",
        f"numberOfSubdomains  {n};",
        "",
        f"method              {method};",
    ]
    if method == "simple":
        nx, ny, nz = simple_split(n)
        lines += [
            "",
            "coeffs",
            "{",
            f"    n               ({nx} {ny} {nz});",
            "}",
        ]
    lines += _footer()
    return "\n".join(lines) + "\n"


def render_fv_schemes() -> str:
    """``system/fvSchemes``. Required by ``fvMesh``; DSMC solves no PDE."""
    lines = _header("fvSchemes",
                    "Empty: dsmcFoam solves no field equations, but fvMesh "
                    "requires the file.", location="system")
    lines += [
        "ddtSchemes      { default none; }",
        "gradSchemes     { default none; }",
        "divSchemes      { default none; }",
        "laplacianSchemes { default none; }",
        "interpolationSchemes { default none; }",
        "snGradSchemes   { default none; }",
    ]
    lines += _footer()
    return "\n".join(lines) + "\n"


def render_fv_solution() -> str:
    """``system/fvSolution``. Required by ``fvMesh``; DSMC solves no PDE."""
    lines = _header("fvSolution",
                    "Empty: dsmcFoam solves no linear systems, but fvMesh "
                    "requires the file.", location="system")
    lines += ["solvers         { }"]
    lines += _footer()
    return "\n".join(lines) + "\n"


def write_case_dictionaries(case_dir: Path, cfg, geom, exit_state,
                            run) -> list[Path]:
    """Write every generated OpenFOAM dictionary for a case.

    Returns:
        The paths written.
    """
    case_dir = Path(case_dir)
    system = case_dir / "system"
    constant = case_dir / "constant"

    return [
        write_lines(constant / "dsmcProperties",
                    render_dsmc_properties(cfg, geom, exit_state, run).splitlines()),
        write_lines(system / "controlDict",
                    render_control_dict(cfg, run).splitlines()),
        write_lines(system / "dsmcInitialiseDict",
                    render_dsmc_initialise_dict(cfg).splitlines()),
        write_lines(system / "decomposeParDict",
                    render_decompose_par_dict(cfg).splitlines()),
        write_lines(system / "fvSchemes", render_fv_schemes().splitlines()),
        write_lines(system / "fvSolution", render_fv_solution().splitlines()),
    ]
